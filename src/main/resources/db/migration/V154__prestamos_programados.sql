CREATE TRIGGER prestamo_cuota_inmutable BEFORE UPDATE OR DELETE ON prestamo_cuota FOR EACH ROW EXECUTE FUNCTION proteger_personal_historial();
CREATE TRIGGER prestamo_cuota_abono_inmutable BEFORE UPDATE OR DELETE ON prestamo_cuota_abono FOR EACH ROW EXECUTE FUNCTION proteger_personal_historial();
CREATE TRIGGER prestamo_cuota_cero_inmutable BEFORE UPDATE OR DELETE ON prestamo_cuota_cero FOR EACH ROW EXECUTE FUNCTION proteger_personal_historial();
CREATE OR REPLACE VIEW prestamo_saldo AS
 SELECT p.id,p.institucion_id,p.empleado_id,
 coalesce(en.importe,0)+CASE WHEN en.prestamo_id IS NULL THEN 0 ELSE coalesce(pl.intereses,0) END-coalesce(a.abonado,0)-coalesce(z.abonado,0) saldo
 FROM prestamo_empleado p LEFT JOIN prestamo_entrega en ON en.prestamo_id=p.id
 LEFT JOIN LATERAL(SELECT sum(interes_nuevo) intereses FROM prestamo_plan WHERE prestamo_id=p.id AND (id=en.plan_id OR clase='REESTRUCTURACION'))pl ON true
 LEFT JOIN LATERAL(SELECT sum(an.importe) abonado FROM prestamo_abono_nomina an JOIN nomina_pago_intento ni ON ni.id=an.pago_id WHERE an.prestamo_id=p.id AND ni.estado='PAGADO')a ON true
 LEFT JOIN LATERAL(SELECT sum(an.capital+an.interes) abonado FROM prestamo_cuota_cero an JOIN prestamo_plan zp ON zp.id=an.plan_id WHERE zp.prestamo_id=p.id)z ON true;
CREATE VIEW prestamo_cuota_pendiente AS
 SELECT c.*,pl.prestamo_id FROM prestamo_cuota c JOIN prestamo_plan pl ON pl.id=c.plan_id
 WHERE NOT EXISTS(SELECT 1 FROM prestamo_cuota_abono a JOIN nomina_pago_intento ni ON ni.id=a.pago_id WHERE a.plan_id=c.plan_id AND a.numero=c.numero AND ni.estado='PAGADO')
 AND NOT EXISTS(SELECT 1 FROM prestamo_cuota_cero a WHERE a.plan_id=c.plan_id AND a.numero=c.numero);
CREATE FUNCTION validar_cuota_abono_programada() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 PERFORM 1 FROM prestamo_empleado p JOIN prestamo_plan pl ON pl.prestamo_id=p.id WHERE pl.id=NEW.plan_id FOR UPDATE OF p;
 IF NOT EXISTS(SELECT 1 FROM prestamo_cuota c JOIN prestamo_plan pl ON pl.id=c.plan_id
 JOIN nomina_pago_intento ni ON ni.id=NEW.pago_id AND ni.estado='PAGADO'
 JOIN nomina_borrador_empleado ne ON ne.id=ni.fila_id
 JOIN prestamo_empleado p ON p.id=pl.prestamo_id AND p.empleado_id=ne.empleado_id AND p.institucion_id=ne.institucion_id
 JOIN prestamo_abono_nomina an ON an.pago_id=ni.id AND an.prestamo_id=p.id
 CROSS JOIN LATERAL jsonb_array_elements(ne.fuentes->'prestamos')x
 CROSS JOIN LATERAL jsonb_array_elements(x->'cuotas_programadas')q
 WHERE c.plan_id=NEW.plan_id AND c.numero=NEW.numero AND c.capital=NEW.capital AND c.interes=NEW.interes
 AND (x->>'id')::bigint=p.id AND (q->>'plan_id')::bigint=c.plan_id AND (q->>'numero')::int=c.numero
 AND (q->>'capital')::numeric=c.capital AND (q->>'interes')::numeric=c.interes)
 OR EXISTS(SELECT 1 FROM prestamo_cuota_abono a JOIN nomina_pago_intento ni ON ni.id=a.pago_id WHERE a.plan_id=NEW.plan_id AND a.numero=NEW.numero AND ni.estado='PAGADO')
 OR EXISTS(SELECT 1 FROM prestamo_cuota_cero a WHERE a.plan_id=NEW.plan_id AND a.numero=NEW.numero)
 THEN RAISE EXCEPTION 'Cuota ya abonada o sin pago y condiciones coincidentes'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER validar_cuota_abono_programada BEFORE INSERT ON prestamo_cuota_abono FOR EACH ROW EXECUTE FUNCTION validar_cuota_abono_programada();
CREATE FUNCTION verificar_abono_programado_completo() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF EXISTS(SELECT 1 FROM prestamo_empleado WHERE id=NEW.prestamo_id AND programado)
 AND NEW.importe<>(SELECT coalesce(sum(a.capital+a.interes),0) FROM prestamo_cuota_abono a JOIN prestamo_plan pl ON pl.id=a.plan_id WHERE a.pago_id=NEW.pago_id AND pl.prestamo_id=NEW.prestamo_id)
 THEN RAISE EXCEPTION 'Abono de préstamo sin distribución completa de capital e interés'; END IF;RETURN NEW;
END $$;
CREATE CONSTRAINT TRIGGER prestamo_abono_programado_completo AFTER INSERT ON prestamo_abono_nomina DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION verificar_abono_programado_completo();
CREATE FUNCTION verificar_plan_prestamo() RETURNS trigger LANGUAGE plpgsql AS $$ DECLARE pl prestamo_plan%ROWTYPE; BEGIN
 SELECT * INTO pl FROM prestamo_plan WHERE id=NEW.id;
 IF NOT EXISTS(SELECT 1 FROM prestamo_empleado p JOIN usuario u ON u.id=pl.usuario_id AND u.institucion_id=p.institucion_id AND u.estado='ACTIVO' AND u.tipo_cuenta='ADMINISTRATIVO' WHERE p.id=pl.prestamo_id AND p.programado)
 OR (SELECT count(*) FROM prestamo_cuota WHERE plan_id=pl.id)<>pl.cuotas
 OR (SELECT sum(capital) FROM prestamo_cuota WHERE plan_id=pl.id)<>pl.capital
 OR (SELECT sum(interes) FROM prestamo_cuota WHERE plan_id=pl.id)<>pl.interes_anterior+pl.interes_nuevo
 OR (SELECT min(fecha) FROM prestamo_cuota WHERE plan_id=pl.id)<>pl.inicio
 OR (SELECT max(fecha) FROM prestamo_cuota WHERE plan_id=pl.id)<>pl.fin
 THEN RAISE EXCEPTION 'Programación de préstamo incompleta o importes incompatibles'; END IF;
 RETURN NEW;
END $$;
CREATE CONSTRAINT TRIGGER prestamo_plan_completo AFTER INSERT ON prestamo_plan DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION verificar_plan_prestamo();

CREATE FUNCTION prestamo_fuentes_periodo(emp bigint,inst bigint,inicio date,fin date) RETURNS SETOF jsonb LANGUAGE sql STABLE AS $$
 SELECT to_jsonb(p)||jsonb_build_object('saldo',s.saldo,'cuota',least(p.parcialidad,s.saldo))
 FROM prestamo_empleado p JOIN prestamo_saldo s ON s.id=p.id WHERE p.empleado_id=$1 AND p.institucion_id=$2 AND NOT p.programado AND p.estado='ACTIVO' AND s.saldo>0 AND p.primer_descuento<=$4
 UNION ALL
 SELECT to_jsonb(p)||jsonb_build_object('saldo',s.saldo,'cuota',q.importe,'plan_id',pl.id,'cuotas_programadas',q.cuotas,'fecha_fin',pl.fin,'requiere_reprogramar',s.saldo<>(SELECT coalesce(sum(cp.capital+cp.interes),0) FROM prestamo_cuota_pendiente cp WHERE cp.plan_id=pl.id))
 FROM prestamo_empleado p JOIN prestamo_saldo s ON s.id=p.id
 JOIN LATERAL(SELECT * FROM prestamo_plan WHERE prestamo_id=p.id ORDER BY id DESC LIMIT 1)pl ON true
 JOIN LATERAL(SELECT sum(c.capital+c.interes) importe,jsonb_agg(to_jsonb(c) ORDER BY c.numero) cuotas FROM prestamo_cuota_pendiente c WHERE c.plan_id=pl.id AND c.fecha BETWEEN $3 AND $4)q ON q.importe>0
 WHERE p.empleado_id=$1 AND p.institucion_id=$2 AND p.programado AND p.estado='ACTIVO' AND s.saldo>0 AND pl.descontar_nomina;
$$;

CREATE FUNCTION validar_compensacion_cuota_cero() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 PERFORM 1 FROM prestamo_empleado p JOIN prestamo_plan pl ON pl.prestamo_id=p.id WHERE pl.id=NEW.plan_id FOR UPDATE OF p;
 IF NOT EXISTS(SELECT 1 FROM prestamo_cuota_pendiente c JOIN prestamo_plan pl ON pl.id=c.plan_id JOIN prestamo_empleado p ON p.id=pl.prestamo_id JOIN nomina_cierre_cero nc ON nc.fila_id=NEW.fila_id
 CROSS JOIN LATERAL jsonb_array_elements(nc.detalle->'fuentes'->'prestamos')x
 CROSS JOIN LATERAL jsonb_array_elements(x->'cuotas_programadas')q
 WHERE c.plan_id=NEW.plan_id AND c.numero=NEW.numero AND c.capital=NEW.capital AND c.interes=NEW.interes
 AND (x->>'id')::bigint=p.id AND p.empleado_id=(nc.detalle->>'empleado_id')::bigint AND p.institucion_id=nc.institucion_id
 AND (q->>'plan_id')::bigint=c.plan_id AND (q->>'numero')::integer=c.numero AND (q->>'capital')::numeric=c.capital AND (q->>'interes')::numeric=c.interes)
 THEN RAISE EXCEPTION 'Compensación sin cuota pendiente y liquidación cero coincidentes'; END IF;RETURN NEW;
END $$;
CREATE TRIGGER validar_compensacion_cuota_cero BEFORE INSERT ON prestamo_cuota_cero FOR EACH ROW EXECUTE FUNCTION validar_compensacion_cuota_cero();
CREATE FUNCTION abonar_prestamos_neto_cero() RETURNS trigger LANGUAGE plpgsql AS $$ DECLARE x jsonb;q jsonb;deuda numeric; BEGIN
 FOR x IN SELECT value FROM jsonb_array_elements(NEW.detalle->'fuentes'->'prestamos') LOOP
  PERFORM 1 FROM prestamo_empleado WHERE id=(x->>'id')::bigint AND programado AND institucion_id=NEW.institucion_id FOR UPDATE;
  SELECT saldo INTO deuda FROM prestamo_saldo WHERE id=(x->>'id')::bigint;
  IF deuda IS NULL OR deuda<(x->>'cuota')::numeric OR NOT (x->>'programado')::boolean
  OR (x->>'cuota')::numeric<>(SELECT coalesce(sum((c->>'capital')::numeric+(c->>'interes')::numeric),0) FROM jsonb_array_elements(x->'cuotas_programadas')c)
  THEN RAISE EXCEPTION 'Revisa el saldo y programación del préstamo'; END IF;
  FOR q IN SELECT value FROM jsonb_array_elements(x->'cuotas_programadas') LOOP
   INSERT INTO prestamo_cuota_cero(fila_id,plan_id,numero,capital,interes) VALUES(NEW.fila_id,(q->>'plan_id')::bigint,(q->>'numero')::int,(q->>'capital')::numeric,(q->>'interes')::numeric);
  END LOOP;
  UPDATE prestamo_empleado SET estado=CASE WHEN (SELECT saldo FROM prestamo_saldo WHERE id=(x->>'id')::bigint)=0 THEN 'LIQUIDADO' ELSE 'ACTIVO' END,version=version+1,actualizado_por_id=NEW.usuario_id,actualizado_en=CURRENT_TIMESTAMP,motivo_operacion='Compensación de préstamo en nómina con neto cero' WHERE id=(x->>'id')::bigint;
 END LOOP;RETURN NEW;
END $$;
