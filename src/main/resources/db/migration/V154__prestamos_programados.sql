CREATE FUNCTION proteger_modelo_prestamo() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF NEW.programado IS DISTINCT FROM OLD.programado THEN RAISE EXCEPTION 'Conserva el modelo y el historial original del préstamo'; END IF;RETURN NEW;
END $$;
CREATE TRIGGER proteger_modelo_prestamo BEFORE UPDATE ON prestamo_empleado FOR EACH ROW EXECUTE FUNCTION proteger_modelo_prestamo();
CREATE FUNCTION validar_plan_entrega_prestamo() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF EXISTS(SELECT 1 FROM prestamo_empleado WHERE id=NEW.prestamo_id AND programado)
 AND NOT EXISTS(SELECT 1 FROM prestamo_plan pl WHERE pl.id=NEW.plan_id AND pl.prestamo_id=NEW.prestamo_id AND pl.clase='ALTA' AND pl.capital=NEW.importe AND pl.interes_anterior=0)
 THEN RAISE EXCEPTION 'La entrega requiere la programación inicial coincidente'; END IF;RETURN NEW;
END $$;
CREATE CONSTRAINT TRIGGER validar_plan_entrega_prestamo AFTER INSERT ON prestamo_entrega DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validar_plan_entrega_prestamo();
