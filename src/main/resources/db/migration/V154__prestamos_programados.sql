CREATE TABLE prestamo_plan (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 prestamo_id bigint NOT NULL REFERENCES prestamo_empleado(id),numero integer NOT NULL CHECK(numero>0),
 clase varchar(20) NOT NULL CHECK(clase IN ('ALTA','REESTRUCTURACION')),
 capital numeric(19,2) NOT NULL CHECK(capital>=0),interes_anterior numeric(19,2) NOT NULL CHECK(interes_anterior>=0),
 interes_nuevo numeric(19,2) NOT NULL CHECK(interes_nuevo>=0),
 porcentaje numeric(8,4) NOT NULL CHECK(porcentaje BETWEEN 0 AND 1000),descontar_nomina boolean NOT NULL,
 frecuencia varchar(12) NOT NULL CHECK(frecuencia IN ('MENSUAL','QUINCENAL','SEMANAL')),
 cuotas integer NOT NULL CHECK(cuotas BETWEEN 1 AND 600),inicio date NOT NULL,fin date NOT NULL CHECK(fin>=inicio),
 motivo varchar(2000) NOT NULL CHECK(btrim(motivo)<>''),usuario_id bigint NOT NULL REFERENCES usuario(id),
 ocurrido_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,UNIQUE(prestamo_id,numero),
 CHECK(capital+interes_anterior+interes_nuevo>0)
);
CREATE TABLE prestamo_cuota (
 plan_id bigint NOT NULL REFERENCES prestamo_plan(id),numero integer NOT NULL CHECK(numero>0),fecha date NOT NULL,
 capital numeric(19,2) NOT NULL CHECK(capital>=0),interes numeric(19,2) NOT NULL CHECK(interes>=0),
 PRIMARY KEY(plan_id,numero),CHECK(capital+interes>0)
);
CREATE TABLE prestamo_cuota_abono (
 pago_id bigint NOT NULL REFERENCES nomina_pago_intento(id),plan_id bigint NOT NULL,numero integer NOT NULL,
 capital numeric(19,2) NOT NULL CHECK(capital>=0),interes numeric(19,2) NOT NULL CHECK(interes>=0),
 PRIMARY KEY(pago_id,plan_id,numero),FOREIGN KEY(plan_id,numero) REFERENCES prestamo_cuota(plan_id,numero)
);
-- Compensación auxiliar de cartera contra la liquidación de nómina; no es tesorería.
CREATE TABLE prestamo_cuota_cero (
 fila_id bigint NOT NULL REFERENCES nomina_cierre_cero(fila_id),plan_id bigint NOT NULL,numero integer NOT NULL,
 capital numeric(19,2) NOT NULL CHECK(capital>=0),interes numeric(19,2) NOT NULL CHECK(interes>=0),
 PRIMARY KEY(fila_id,plan_id,numero),FOREIGN KEY(plan_id,numero) REFERENCES prestamo_cuota(plan_id,numero)
);
CREATE INDEX ix_prestamo_plan_actual ON prestamo_plan(prestamo_id,id DESC);
