-- Organización de fuentes existentes; no modifica salarios, conceptos ni borradores.
CREATE TABLE empleado_calendario_nomina (
 empleado_id BIGINT PRIMARY KEY, institucion_id BIGINT NOT NULL, calendario_id BIGINT NOT NULL,
 calendario_texto VARCHAR(210) NOT NULL,
 motivo VARCHAR(2000) NOT NULL CHECK(btrim(motivo)<>''),
 actualizado_por_id BIGINT NOT NULL REFERENCES usuario(id), actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
 FOREIGN KEY(empleado_id,institucion_id) REFERENCES empleado(id,institucion_id),
 FOREIGN KEY(calendario_id,institucion_id) REFERENCES calendario_nomina(id,institucion_id)
);
CREATE INDEX ix_empleado_calendario_nomina ON empleado_calendario_nomina(institucion_id,calendario_id,empleado_id);
CREATE TABLE empleado_calendario_nomina_historial (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empleado_id BIGINT NOT NULL, institucion_id BIGINT NOT NULL,
 ocurrido_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 usuario_id BIGINT NOT NULL REFERENCES usuario(id), motivo VARCHAR(2000) NOT NULL,
 anterior JSONB, nuevo JSONB NOT NULL,
 FOREIGN KEY(empleado_id,institucion_id) REFERENCES empleado(id,institucion_id)
);
CREATE INDEX ix_empleado_calendario_historial ON empleado_calendario_nomina_historial(institucion_id,empleado_id,id);
CREATE TRIGGER tr_empleado_calendario_historial BEFORE UPDATE OR DELETE ON empleado_calendario_nomina_historial
 FOR EACH ROW EXECUTE FUNCTION proteger_personal_historial();
CREATE FUNCTION auditar_empleado_calendario_nomina() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Conserva la configuración y su historial'; END IF;
 IF TG_OP='UPDATE' AND (NEW.empleado_id,NEW.institucion_id) IS DISTINCT FROM (OLD.empleado_id,OLD.institucion_id) THEN
  RAISE EXCEPTION 'El empleado y la institución no se reasignan';
 END IF;
 INSERT INTO empleado_calendario_nomina_historial(empleado_id,institucion_id,usuario_id,motivo,anterior,nuevo)
 VALUES(NEW.empleado_id,NEW.institucion_id,NEW.actualizado_por_id,NEW.motivo,
 CASE WHEN TG_OP='UPDATE' THEN to_jsonb(OLD) END,to_jsonb(NEW));
 RETURN NEW;
END $$;
CREATE TRIGGER tr_empleado_calendario_nomina BEFORE INSERT OR UPDATE OR DELETE ON empleado_calendario_nomina
 FOR EACH ROW EXECUTE FUNCTION auditar_empleado_calendario_nomina();
