CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE institucion (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo                  VARCHAR(50) NOT NULL,
    nombre                  VARCHAR(200) NOT NULL,
    nombre_comercial        VARCHAR(200),
    razon_social            VARCHAR(250),
    rfc                     VARCHAR(13),
    email                   VARCHAR(254),
    telefono                VARCHAR(30),
    sitio_web               VARCHAR(300),
    domicilio_fiscal        TEXT,
    ciudad                  VARCHAR(120),
    estado                  VARCHAR(120),
    codigo_postal           VARCHAR(12),
    pais                    VARCHAR(2),
    logo_archivo_id         BIGINT,
    zona_horaria            VARCHAR(60) NOT NULL DEFAULT 'America/Mexico_City',
    moneda_predeterminada   VARCHAR(3) NOT NULL DEFAULT 'MXN',
    activo                  BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en               TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    creado_por_id           BIGINT,
    actualizado_en          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_por_id      BIGINT,
    version                 BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_institucion_codigo_no_vacio CHECK (btrim(codigo) <> ''),
    CONSTRAINT ck_institucion_nombre_no_vacio CHECK (btrim(nombre) <> ''),
    CONSTRAINT ck_institucion_moneda CHECK (moneda_predeterminada ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_institucion_pais CHECK (pais IS NULL OR pais ~ '^[A-Z]{2}$'),
    CONSTRAINT ck_institucion_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX ux_institucion_codigo_normalizado ON institucion (lower(btrim(codigo)));

CREATE TABLE plantel (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institucion_id      BIGINT NOT NULL REFERENCES institucion(id),
    codigo              VARCHAR(50) NOT NULL,
    nombre              VARCHAR(200) NOT NULL,
    telefono            VARCHAR(30),
    email               VARCHAR(254),
    calle               VARCHAR(200),
    numero_exterior     VARCHAR(30),
    numero_interior     VARCHAR(30),
    colonia             VARCHAR(150),
    ciudad              VARCHAR(120),
    estado              VARCHAR(120),
    codigo_postal       VARCHAR(12),
    pais                VARCHAR(2),
    activo              BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    creado_por_id       BIGINT,
    actualizado_en      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_por_id  BIGINT,
    version             BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_plantel_codigo_no_vacio CHECK (btrim(codigo) <> ''),
    CONSTRAINT ck_plantel_nombre_no_vacio CHECK (btrim(nombre) <> ''),
    CONSTRAINT ck_plantel_pais CHECK (pais IS NULL OR pais ~ '^[A-Z]{2}$'),
    CONSTRAINT ck_plantel_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX ux_plantel_institucion_codigo
    ON plantel (institucion_id, lower(btrim(codigo)));
CREATE INDEX ix_plantel_institucion ON plantel (institucion_id);

CREATE TABLE nivel_educativo (
