    codigo              VARCHAR(50) NOT NULL,
    nombre              VARCHAR(150) NOT NULL,
    descripcion         TEXT,
    orden               INTEGER NOT NULL,
    activo              BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    creado_por_id       BIGINT,
    actualizado_en      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_por_id  BIGINT,
    version             BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_nivel_codigo_no_vacio CHECK (btrim(codigo) <> ''),
    CONSTRAINT ck_nivel_nombre_no_vacio CHECK (btrim(nombre) <> ''),
    CONSTRAINT ck_nivel_orden_positivo CHECK (orden > 0),
    CONSTRAINT ck_nivel_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX ux_nivel_institucion_codigo
    ON nivel_educativo (institucion_id, lower(btrim(codigo)));
CREATE UNIQUE INDEX ux_nivel_institucion_orden
    ON nivel_educativo (institucion_id, orden);
CREATE INDEX ix_nivel_institucion ON nivel_educativo (institucion_id);

CREATE TABLE plantel_nivel (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plantel_id              BIGINT NOT NULL REFERENCES plantel(id),
    nivel_educativo_id      BIGINT NOT NULL REFERENCES nivel_educativo(id),
    clave_centro_trabajo    VARCHAR(30),
    activo                  BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en               TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    creado_por_id           BIGINT,
    actualizado_en          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_por_id      BIGINT,
    version                 BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_plantel_nivel UNIQUE (plantel_id, nivel_educativo_id),
    CONSTRAINT ck_plantel_nivel_version CHECK (version >= 0)
);

CREATE INDEX ix_plantel_nivel_nivel ON plantel_nivel (nivel_educativo_id);

CREATE TABLE grado (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nivel_educativo_id      BIGINT NOT NULL REFERENCES nivel_educativo(id),
