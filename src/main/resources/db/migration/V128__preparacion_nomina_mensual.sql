-- Borradores privados y revisiones históricas. No autoriza ni paga nómina.
CREATE TABLE nomina_borrador (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 institucion_id BIGINT NOT NULL, periodo_id BIGINT NOT NULL,
 nombre VARCHAR(150) NOT NULL CHECK(btrim(nombre)<>''),
 estado VARCHAR(12) NOT NULL DEFAULT 'BORRADOR' CHECK(estado IN ('BORRADOR','CANCELADO')),
 revision_actual INTEGER NOT NULL DEFAULT 1 CHECK(revision_actual>0),
 motivo_operacion VARCHAR(2000) NOT NULL CHECK(btrim(motivo_operacion)<>''),
 creado_por_id BIGINT NOT NULL REFERENCES usuario(id), creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado_por_id BIGINT NOT NULL REFERENCES usuario(id), actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
 FOREIGN KEY(periodo_id,institucion_id) REFERENCES periodo_nomina(id,institucion_id),
 UNIQUE(id,institucion_id,periodo_id)
);
CREATE TABLE nomina_borrador_revision (
 borrador_id BIGINT NOT NULL, numero INTEGER NOT NULL CHECK(numero>0), institucion_id BIGINT NOT NULL, periodo_id BIGINT NOT NULL,
 periodo_codigo VARCHAR(50) NOT NULL, periodo_nombre VARCHAR(150) NOT NULL, calendario_id BIGINT NOT NULL,
 calendario_texto VARCHAR(450) NOT NULL, fecha_inicio DATE NOT NULL, fecha_fin DATE NOT NULL, fecha_pago DATE NOT NULL,
 moneda VARCHAR(3) NOT NULL, datos_periodo JSONB NOT NULL, sello_periodo VARCHAR(64) NOT NULL,
 motivo VARCHAR(2000) NOT NULL CHECK(btrim(motivo)<>''), creado_por_id BIGINT NOT NULL REFERENCES usuario(id),
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(borrador_id,numero),
 FOREIGN KEY(borrador_id,institucion_id,periodo_id) REFERENCES nomina_borrador(id,institucion_id,periodo_id),
 UNIQUE(borrador_id,numero,institucion_id,periodo_id,fecha_inicio,fecha_fin),
 CHECK(fecha_inicio=date_trunc('month',fecha_inicio)::date AND fecha_fin=(fecha_inicio+INTERVAL '1 month - 1 day')::date)
);
CREATE TABLE nomina_borrador_empleado (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 borrador_id BIGINT NOT NULL, revision INTEGER NOT NULL, institucion_id BIGINT NOT NULL, periodo_id BIGINT NOT NULL,
 empleado_id BIGINT NOT NULL, empleado_codigo VARCHAR(50) NOT NULL, empleado_nombre VARCHAR(400) NOT NULL,
 fecha_inicio DATE NOT NULL, fecha_fin DATE NOT NULL,
 sueldo NUMERIC(19,2) NOT NULL CHECK(sueldo>0), percepciones NUMERIC(19,2) NOT NULL CHECK(percepciones>=0),
 deducciones NUMERIC(19,2) NOT NULL CHECK(deducciones>=0), aportaciones NUMERIC(19,2) NOT NULL CHECK(aportaciones>=0),
 propuesto NUMERIC(19,2) NOT NULL CHECK(propuesto>=0 AND propuesto=sueldo+percepciones-deducciones),
 moneda VARCHAR(3) NOT NULL, fuentes JSONB NOT NULL, sello VARCHAR(64) NOT NULL, activo BOOLEAN NOT NULL DEFAULT TRUE,
 FOREIGN KEY(empleado_id,institucion_id) REFERENCES empleado(id,institucion_id),
 FOREIGN KEY(borrador_id,revision,institucion_id,periodo_id,fecha_inicio,fecha_fin)
  REFERENCES nomina_borrador_revision(borrador_id,numero,institucion_id,periodo_id,fecha_inicio,fecha_fin),
 UNIQUE(borrador_id,revision,empleado_id),
 EXCLUDE USING gist(empleado_id WITH =,daterange(fecha_inicio,fecha_fin,'[]') WITH &&) WHERE(activo)
);
CREATE UNIQUE INDEX ux_nomina_borrador_empleado_periodo ON nomina_borrador_empleado(empleado_id,periodo_id) WHERE activo;
CREATE INDEX ix_nomina_borrador_institucion ON nomina_borrador(institucion_id,id);
CREATE INDEX ix_nomina_borrador_revision ON nomina_borrador_revision(institucion_id,periodo_id,borrador_id,numero);
CREATE INDEX ix_nomina_borrador_empleado ON nomina_borrador_empleado(institucion_id,borrador_id,revision,id);
CREATE TABLE nomina_borrador_historial (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, borrador_id BIGINT NOT NULL REFERENCES nomina_borrador(id),
 institucion_id BIGINT NOT NULL REFERENCES institucion(id), operacion VARCHAR(6) NOT NULL,
 usuario_id BIGINT NOT NULL REFERENCES usuario(id), ocurrido_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, datos JSONB NOT NULL
);
CREATE INDEX ix_nomina_borrador_historial ON nomina_borrador_historial(institucion_id,borrador_id,id DESC);
CREATE FUNCTION proteger_nomina_borrador() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Conserva el borrador y sus revisiones'; END IF;
 IF TG_TABLE_NAME='nomina_borrador' THEN
  IF OLD.estado='CANCELADO' OR (NEW.id,NEW.institucion_id,NEW.periodo_id,NEW.creado_por_id,NEW.creado_en)
    IS DISTINCT FROM (OLD.id,OLD.institucion_id,OLD.periodo_id,OLD.creado_por_id,OLD.creado_en) THEN
   RAISE EXCEPTION 'Identidad inmutable; cancelado sólo consulta';
  END IF;
 ELSIF TG_TABLE_NAME='nomina_borrador_empleado' THEN
  IF NOT OLD.activo OR NEW.activo OR (to_jsonb(NEW)-'activo') IS DISTINCT FROM (to_jsonb(OLD)-'activo') THEN
   RAISE EXCEPTION 'Conserva la fotografía histórica del empleado';
  END IF;
 ELSE RAISE EXCEPTION 'La revisión histórica no se modifica';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_nomina_borrador_proteger BEFORE UPDATE OR DELETE ON nomina_borrador FOR EACH ROW EXECUTE FUNCTION proteger_nomina_borrador();
CREATE TRIGGER tr_nomina_revision_proteger BEFORE UPDATE OR DELETE ON nomina_borrador_revision FOR EACH ROW EXECUTE FUNCTION proteger_nomina_borrador();
CREATE TRIGGER tr_nomina_empleado_proteger BEFORE UPDATE OR DELETE ON nomina_borrador_empleado FOR EACH ROW EXECUTE FUNCTION proteger_nomina_borrador();
CREATE FUNCTION registrar_nomina_borrador_historia() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 INSERT INTO nomina_borrador_historial(borrador_id,institucion_id,operacion,usuario_id,datos)
 VALUES(NEW.id,NEW.institucion_id,TG_OP,NEW.actualizado_por_id,
 jsonb_build_object('antes',CASE WHEN TG_OP='UPDATE' THEN to_jsonb(OLD) ELSE NULL END,'despues',to_jsonb(NEW)));
 RETURN NEW;
END $$;
CREATE TRIGGER tr_nomina_borrador_historia AFTER INSERT OR UPDATE ON nomina_borrador FOR EACH ROW EXECUTE FUNCTION registrar_nomina_borrador_historia();
CREATE TRIGGER tr_nomina_historial_inmutable BEFORE UPDATE OR DELETE ON nomina_borrador_historial FOR EACH ROW EXECUTE FUNCTION proteger_personal_historial();
