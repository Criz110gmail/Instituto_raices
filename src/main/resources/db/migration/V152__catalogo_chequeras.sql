CREATE TABLE chequera (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cuenta_id BIGINT NOT NULL REFERENCES cuenta_financiera(id),
 institucion_id BIGINT NOT NULL REFERENCES institucion(id),
 nombre VARCHAR(150) NOT NULL CHECK(btrim(nombre)<>''),
 folio_inicial BIGINT NOT NULL CHECK(folio_inicial BETWEEN 1 AND 999999999999),
 folio_final BIGINT NOT NULL CHECK(folio_final BETWEEN folio_inicial AND 999999999999),
 activo BOOLEAN NOT NULL DEFAULT true,
 motivo VARCHAR(2000) NOT NULL CHECK(btrim(motivo)<>''),
 creado_por_id BIGINT NOT NULL REFERENCES usuario(id),
 actualizado_por_id BIGINT NOT NULL REFERENCES usuario(id),
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
 EXCLUDE USING gist(cuenta_id WITH =,int8range(folio_inicial,folio_final,'[]') WITH &&)
);
CREATE INDEX ix_chequera_cuenta ON chequera(cuenta_id,id);
CREATE TABLE chequera_historial (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 chequera_id BIGINT NOT NULL REFERENCES chequera(id),
 institucion_id BIGINT NOT NULL REFERENCES institucion(id),
 usuario_id BIGINT NOT NULL REFERENCES usuario(id),
 ocurrido_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 anterior JSONB, actual JSONB NOT NULL
);
CREATE INDEX ix_chequera_historial ON chequera_historial(chequera_id,id DESC);
CREATE FUNCTION validar_chequera() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE banco cuenta_financiera%ROWTYPE;
BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Las chequeras se desactivan, no se borran'; END IF;
 SELECT * INTO banco FROM cuenta_financiera WHERE id=NEW.cuenta_id FOR UPDATE;
 IF banco.id IS NULL OR banco.tipo<>'BANCO' OR banco.institucion_id<>NEW.institucion_id THEN
  RAISE EXCEPTION 'La chequera requiere una cuenta bancaria de la misma institución';
 END IF;
 IF NOT EXISTS(SELECT 1 FROM usuario WHERE id=NEW.actualizado_por_id AND institucion_id=NEW.institucion_id AND estado='ACTIVO' AND tipo_cuenta='ADMINISTRATIVO') THEN
  RAISE EXCEPTION 'Se requiere un usuario administrativo activo de la institución';
 END IF;
 IF TG_OP='UPDATE' THEN
  IF (NEW.cuenta_id,NEW.institucion_id,NEW.creado_por_id,NEW.creado_en) IS DISTINCT FROM (OLD.cuenta_id,OLD.institucion_id,OLD.creado_por_id,OLD.creado_en) THEN
   RAISE EXCEPTION 'No se cambia la cuenta ni la identidad original de la chequera';
  END IF;
  IF NEW.version<>OLD.version+1 THEN RAISE EXCEPTION 'Versión de chequera inválida'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER validar_chequera BEFORE INSERT OR UPDATE OR DELETE ON chequera FOR EACH ROW EXECUTE FUNCTION validar_chequera();
CREATE FUNCTION auditar_chequera() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO chequera_historial(chequera_id,institucion_id,usuario_id,anterior,actual)
 VALUES(NEW.id,NEW.institucion_id,NEW.actualizado_por_id,CASE WHEN TG_OP='UPDATE' THEN to_jsonb(OLD) END,to_jsonb(NEW));
 RETURN NEW;
END $$;
CREATE TRIGGER auditar_chequera AFTER INSERT OR UPDATE ON chequera FOR EACH ROW EXECUTE FUNCTION auditar_chequera();
CREATE FUNCTION chequera_historial_inmutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'El historial de chequeras es inmutable'; END $$;
CREATE TRIGGER chequera_historial_inmutable BEFORE UPDATE OR DELETE ON chequera_historial FOR EACH ROW EXECUTE FUNCTION chequera_historial_inmutable();
CREATE FUNCTION conservar_cuenta_chequeras() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF (NEW.tipo,NEW.institucion_id) IS DISTINCT FROM (OLD.tipo,OLD.institucion_id)
 AND EXISTS(SELECT 1 FROM chequera WHERE cuenta_id=OLD.id) THEN
  RAISE EXCEPTION 'La cuenta tiene chequeras: no se cambia su tipo ni institución';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER conservar_cuenta_chequeras BEFORE UPDATE ON cuenta_financiera FOR EACH ROW EXECUTE FUNCTION conservar_cuenta_chequeras();
