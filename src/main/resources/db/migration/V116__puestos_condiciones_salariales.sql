-- Configuración privada; no crea nóminas, pagos ni movimientos financieros.
CREATE TABLE puesto_laboral (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 institucion_id BIGINT NOT NULL REFERENCES institucion(id),
 codigo VARCHAR(50) NOT NULL, nombre VARCHAR(150) NOT NULL, descripcion VARCHAR(2000),
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, creado_por_id BIGINT NOT NULL REFERENCES usuario(id),
 actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, actualizado_por_id BIGINT NOT NULL REFERENCES usuario(id),
 version BIGINT NOT NULL DEFAULT 0,
 UNIQUE(institucion_id,codigo), UNIQUE(id,institucion_id),
 CHECK(codigo=upper(btrim(codigo)) AND codigo<>'' AND btrim(nombre)<>'')
);
CREATE TABLE condicion_salarial (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empleado_id BIGINT NOT NULL, institucion_id BIGINT NOT NULL,
 puesto_id BIGINT NOT NULL, puesto_codigo VARCHAR(50) NOT NULL, puesto_nombre VARCHAR(150) NOT NULL,
 importe_bruto NUMERIC(19,2) NOT NULL CHECK(importe_bruto>0), moneda VARCHAR(3) NOT NULL,
 base VARCHAR(20) NOT NULL CHECK(base IN ('MENSUAL','SEMANAL','DIARIA','POR_HORA')),
 frecuencia VARCHAR(20) NOT NULL CHECK(frecuencia IN ('MENSUAL','QUINCENAL','SEMANAL')),
 fecha_inicio DATE NOT NULL, fecha_fin DATE,
 estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVA' CHECK(estado IN ('ACTIVA','CANCELADA')),
 motivo VARCHAR(2000) NOT NULL CHECK(btrim(motivo)<>''),
 anterior_id BIGINT, fin_anterior DATE,
 motivo_operacion VARCHAR(2000) NOT NULL CHECK(btrim(motivo_operacion)<>''),
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, creado_por_id BIGINT NOT NULL REFERENCES usuario(id),
 actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, actualizado_por_id BIGINT NOT NULL REFERENCES usuario(id),
 version BIGINT NOT NULL DEFAULT 0,
 FOREIGN KEY(empleado_id,institucion_id) REFERENCES empleado(id,institucion_id),
 FOREIGN KEY(puesto_id,institucion_id) REFERENCES puesto_laboral(id,institucion_id),
 UNIQUE(id,empleado_id),
 FOREIGN KEY(anterior_id,empleado_id) REFERENCES condicion_salarial(id,empleado_id),
 CHECK(fecha_fin IS NULL OR fecha_fin>=fecha_inicio), CHECK(moneda ~ '^[A-Z]{3}$'),
 EXCLUDE USING gist(empleado_id WITH =,daterange(fecha_inicio,fecha_fin,'[]') WITH &&) WHERE(estado='ACTIVA')
);
CREATE INDEX ix_condicion_empleado_fecha ON condicion_salarial(empleado_id,fecha_inicio DESC,id DESC);
CREATE INDEX ix_puesto_institucion_nombre ON puesto_laboral(institucion_id,nombre,id);
CREATE TABLE personal_salarial_historial (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 institucion_id BIGINT NOT NULL REFERENCES institucion(id), empleado_id BIGINT REFERENCES empleado(id),
 tipo VARCHAR(20) NOT NULL, registro_id BIGINT NOT NULL, operacion VARCHAR(20) NOT NULL,
 ocurrido_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, usuario_id BIGINT NOT NULL REFERENCES usuario(id),
 datos JSONB NOT NULL
);
CREATE INDEX ix_salarial_historial_empleado ON personal_salarial_historial(empleado_id,id DESC);
CREATE FUNCTION proteger_configuracion_salarial() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Conserva la configuración salarial y su historial'; END IF;
 IF TG_OP='UPDATE' THEN
  IF TG_TABLE_NAME='puesto_laboral' THEN
   IF NEW.institucion_id<>OLD.institucion_id THEN RAISE EXCEPTION 'El puesto no cambia de institución'; END IF;
  ELSE
   IF (to_jsonb(NEW)-ARRAY['fecha_fin','estado','motivo_operacion','actualizado_en','actualizado_por_id','version'])
      IS DISTINCT FROM (to_jsonb(OLD)-ARRAY['fecha_fin','estado','motivo_operacion','actualizado_en','actualizado_por_id','version'])
      OR OLD.estado='CANCELADA' THEN
    RAISE EXCEPTION 'La condición salarial conserva su fotografía original; registra otra vigencia';
   END IF;
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_puesto_proteger BEFORE UPDATE OR DELETE ON puesto_laboral FOR EACH ROW EXECUTE FUNCTION proteger_configuracion_salarial();
CREATE TRIGGER tr_condicion_proteger BEFORE UPDATE OR DELETE ON condicion_salarial FOR EACH ROW EXECUTE FUNCTION proteger_configuracion_salarial();
CREATE FUNCTION registrar_historia_salarial() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO personal_salarial_historial(institucion_id,empleado_id,tipo,registro_id,operacion,usuario_id,datos)
 VALUES(NEW.institucion_id,CASE WHEN TG_TABLE_NAME='condicion_salarial' THEN (to_jsonb(NEW)->>'empleado_id')::BIGINT ELSE NULL END,
 CASE WHEN TG_TABLE_NAME='condicion_salarial' THEN 'CONDICION' ELSE 'PUESTO' END,NEW.id,TG_OP,NEW.actualizado_por_id,
 jsonb_build_object('antes',CASE WHEN TG_OP='UPDATE' THEN to_jsonb(OLD) ELSE NULL END,'despues',to_jsonb(NEW)));
 RETURN NEW;
END $$;
CREATE TRIGGER tr_puesto_historia AFTER INSERT OR UPDATE ON puesto_laboral FOR EACH ROW EXECUTE FUNCTION registrar_historia_salarial();
CREATE TRIGGER tr_condicion_historia AFTER INSERT OR UPDATE ON condicion_salarial FOR EACH ROW EXECUTE FUNCTION registrar_historia_salarial();
CREATE TRIGGER tr_salarial_historia_inmutable BEFORE UPDATE OR DELETE ON personal_salarial_historial FOR EACH ROW EXECUTE FUNCTION proteger_personal_historial();
