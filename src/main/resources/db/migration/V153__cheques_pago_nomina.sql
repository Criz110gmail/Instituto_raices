-- Emisión nominativa por fuente de pago; no modifica pagos históricos ni asigna permisos.
ALTER TABLE nomina_pago_fuente DROP CONSTRAINT nomina_pago_fuente_medio_check;
ALTER TABLE nomina_pago_fuente ADD CONSTRAINT nomina_pago_fuente_medio_check CHECK(medio IN ('EFECTIVO','TRANSFERENCIA','CHEQUE'));
CREATE TABLE cheque_nomina (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 institucion_id BIGINT NOT NULL REFERENCES institucion(id),
 cuenta_id BIGINT NOT NULL REFERENCES cuenta_financiera(id),
 chequera_id BIGINT NOT NULL REFERENCES chequera(id),
 chequera_nombre VARCHAR(150) NOT NULL, chequera_version BIGINT NOT NULL,
 pago_id BIGINT NOT NULL, ordinal INTEGER NOT NULL,
 folio BIGINT NOT NULL CHECK(folio BETWEEN 1 AND 999999999999),
 fecha_emision DATE NOT NULL, beneficiario VARCHAR(250) NOT NULL CHECK(btrim(beneficiario)<>''),
 importe NUMERIC(19,2) NOT NULL CHECK(importe>0), moneda VARCHAR(3) NOT NULL,
 usuario_id BIGINT NOT NULL REFERENCES usuario(id), ocurrido_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(cuenta_id,folio), UNIQUE(pago_id,ordinal),
 FOREIGN KEY(pago_id,ordinal) REFERENCES nomina_pago_fuente(pago_id,ordinal)
);
CREATE INDEX ix_cheque_nomina_chequera ON cheque_nomina(chequera_id,folio);
CREATE TABLE cheque_nomina_cancelacion (
 cheque_id BIGINT PRIMARY KEY REFERENCES cheque_nomina(id),
 movimiento_id BIGINT NOT NULL UNIQUE REFERENCES movimiento_financiero(id),
 usuario_id BIGINT NOT NULL REFERENCES usuario(id), ocurrido_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 referencia VARCHAR(150) NOT NULL CHECK(btrim(referencia)<>''),
 motivo VARCHAR(2000) NOT NULL CHECK(btrim(motivo)<>''),
 no_cobrable_confirmado BOOLEAN NOT NULL CHECK(no_cobrable_confirmado)
);
CREATE TRIGGER cheque_nomina_inmutable BEFORE UPDATE OR DELETE ON cheque_nomina FOR EACH ROW EXECUTE FUNCTION proteger_personal_historial();
CREATE TRIGGER cheque_nomina_cancelacion_inmutable BEFORE UPDATE OR DELETE ON cheque_nomina_cancelacion FOR EACH ROW EXECUTE FUNCTION proteger_personal_historial();
CREATE OR REPLACE FUNCTION validar_fuente_nomina() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF EXISTS(SELECT 1 FROM nomina_pago_intento WHERE id=NEW.pago_id) THEN
  RAISE EXCEPTION 'Un pago ya registrado conserva sus fuentes originales'; END IF;
 IF NOT EXISTS(SELECT 1 FROM movimiento_financiero m JOIN cuenta_financiera c ON c.id=m.cuenta_id
 WHERE m.id=NEW.movimiento_id AND m.cuenta_id=NEW.cuenta_id AND m.clase='NOMINA' AND m.direccion='EGRESO'
 AND m.monto=NEW.importe AND m.clave_idempotencia='NOMINA-EMP:'||NEW.pago_id||':'||NEW.ordinal
 AND ((NEW.medio='EFECTIVO' AND c.tipo='CAJA') OR (NEW.medio IN ('TRANSFERENCIA','CHEQUE') AND c.tipo='BANCO')))
 THEN RAISE EXCEPTION 'Fuente de nómina sin egreso y medio coincidentes'; END IF; RETURN NEW;
END $$;
CREATE FUNCTION validar_cheque_nomina() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE ch chequera%ROWTYPE; banco cuenta_financiera%ROWTYPE; hoy DATE;
BEGIN
 SELECT * INTO banco FROM cuenta_financiera WHERE id=NEW.cuenta_id FOR UPDATE;
 SELECT * INTO ch FROM chequera WHERE id=NEW.chequera_id FOR UPDATE;
 SELECT (CURRENT_TIMESTAMP AT TIME ZONE zona_horaria)::date INTO hoy FROM institucion WHERE id=NEW.institucion_id AND activo;
 IF banco.id IS NULL OR banco.tipo<>'BANCO' OR NOT banco.activo OR banco.institucion_id<>NEW.institucion_id
 OR ch.id IS NULL OR NOT ch.activo OR ch.cuenta_id<>banco.id OR ch.institucion_id<>NEW.institucion_id
 OR NEW.folio NOT BETWEEN ch.folio_inicial AND ch.folio_final OR NEW.chequera_version<>ch.version
 OR NEW.chequera_nombre<>ch.nombre OR NEW.moneda<>banco.moneda OR hoy IS NULL OR NEW.fecha_emision>hoy
 THEN RAISE EXCEPTION 'Cheque sin cuenta, chequera, folio o fecha compatibles'; END IF;
 IF NOT EXISTS(SELECT 1 FROM nomina_pago_fuente WHERE pago_id=NEW.pago_id AND ordinal=NEW.ordinal AND medio='CHEQUE' AND cuenta_id=NEW.cuenta_id AND importe=NEW.importe)
 OR NOT EXISTS(SELECT 1 FROM usuario WHERE id=NEW.usuario_id AND institucion_id=NEW.institucion_id AND estado='ACTIVO' AND tipo_cuenta='ADMINISTRATIVO')
 THEN RAISE EXCEPTION 'Cheque sin fuente o responsable compatibles'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER cheque_nomina_validar BEFORE INSERT ON cheque_nomina FOR EACH ROW EXECUTE FUNCTION validar_cheque_nomina();
CREATE FUNCTION validar_cancelacion_cheque_nomina() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF NOT EXISTS(SELECT 1 FROM cheque_nomina ch JOIN nomina_pago_fuente f ON f.pago_id=ch.pago_id AND f.ordinal=ch.ordinal
 JOIN nomina_pago_fuente_reversa r ON r.pago_id=f.pago_id AND r.ordinal=f.ordinal
 JOIN movimiento_financiero m ON m.id=r.movimiento_id
 JOIN usuario u ON u.id=NEW.usuario_id AND u.institucion_id=ch.institucion_id AND u.estado='ACTIVO' AND u.tipo_cuenta='ADMINISTRATIVO'
 WHERE ch.id=NEW.cheque_id AND r.movimiento_id=NEW.movimiento_id AND m.cuenta_id=ch.cuenta_id
 AND m.reversa_de_id=f.movimiento_id AND m.monto=ch.importe AND m.clase='NOMINA_REVERSO' AND m.direccion='INGRESO')
 THEN RAISE EXCEPTION 'Cancelación de cheque sin compensación exacta'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER cheque_nomina_cancelacion_validar BEFORE INSERT ON cheque_nomina_cancelacion FOR EACH ROW EXECUTE FUNCTION validar_cancelacion_cheque_nomina();
CREATE FUNCTION verificar_documento_cheque_nomina() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF TG_TABLE_NAME='nomina_pago_fuente' AND NEW.medio='CHEQUE' AND NOT EXISTS(SELECT 1 FROM cheque_nomina WHERE pago_id=NEW.pago_id AND ordinal=NEW.ordinal) THEN
  RAISE EXCEPTION 'La fuente cheque requiere su documento de emisión';
 END IF;
 RETURN NEW;
END $$;
CREATE CONSTRAINT TRIGGER nomina_fuente_cheque_completo AFTER INSERT ON nomina_pago_fuente DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION verificar_documento_cheque_nomina();
CREATE FUNCTION verificar_cheque_cancelado_nomina() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF EXISTS(SELECT 1 FROM cheque_nomina ch LEFT JOIN cheque_nomina_cancelacion cc ON cc.cheque_id=ch.id WHERE ch.pago_id=NEW.pago_id AND ch.ordinal=NEW.ordinal AND cc.cheque_id IS NULL) THEN
  RAISE EXCEPTION 'La recuperación requiere conservar la cancelación del cheque';
 END IF;
 RETURN NEW;
END $$;
CREATE CONSTRAINT TRIGGER nomina_fuente_cheque_cancelado AFTER INSERT ON nomina_pago_fuente_reversa DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION verificar_cheque_cancelado_nomina();
CREATE FUNCTION conservar_rango_chequera_emitida() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF (NEW.folio_inicial,NEW.folio_final) IS DISTINCT FROM (OLD.folio_inicial,OLD.folio_final)
 AND EXISTS(SELECT 1 FROM cheque_nomina WHERE chequera_id=OLD.id) THEN
  RAISE EXCEPTION 'La chequera tiene cheques emitidos: conserva su rango original';
 END IF; RETURN NEW;
END $$;
CREATE TRIGGER conservar_rango_chequera_emitida BEFORE UPDATE ON chequera FOR EACH ROW EXECUTE FUNCTION conservar_rango_chequera_emitida();
