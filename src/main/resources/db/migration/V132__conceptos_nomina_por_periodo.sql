-- Conceptos ocasionales: configurarlos no consume un pago ni modifica revisiones previas.
CREATE TABLE concepto_empleado_periodo (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 institucion_id BIGINT NOT NULL, empleado_id BIGINT NOT NULL, periodo_id BIGINT NOT NULL,
 concepto_id BIGINT NOT NULL, concepto_codigo VARCHAR(50) NOT NULL, concepto_nombre VARCHAR(150) NOT NULL,
 naturaleza VARCHAR(25) NOT NULL CHECK(naturaleza IN ('PERCEPCION','DEDUCCION','APORTACION_PATRONAL')),
 concepto_version BIGINT NOT NULL, importe NUMERIC(19,2) NOT NULL CHECK(importe>0), moneda VARCHAR(3) NOT NULL,
 fecha_inicio DATE NOT NULL, fecha_fin DATE NOT NULL CHECK(fecha_fin>=fecha_inicio),
 periodo_texto VARCHAR(250) NOT NULL, sello_periodo VARCHAR(64) NOT NULL,
 estado VARCHAR(10) NOT NULL DEFAULT 'ACTIVA' CHECK(estado IN ('ACTIVA','CANCELADA')),
 motivo VARCHAR(2000) NOT NULL CHECK(btrim(motivo)<>''), motivo_operacion VARCHAR(2000) NOT NULL CHECK(btrim(motivo_operacion)<>''),
 creado_por_id BIGINT NOT NULL REFERENCES usuario(id), creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado_por_id BIGINT NOT NULL REFERENCES usuario(id), actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 version BIGINT NOT NULL DEFAULT 0,
 FOREIGN KEY(empleado_id,institucion_id) REFERENCES empleado(id,institucion_id),
 FOREIGN KEY(periodo_id,institucion_id) REFERENCES periodo_nomina(id,institucion_id),
 FOREIGN KEY(concepto_id,institucion_id) REFERENCES concepto_nomina(id,institucion_id)
);
CREATE UNIQUE INDEX ux_concepto_empleado_periodo_activo ON concepto_empleado_periodo(empleado_id,periodo_id,concepto_id) WHERE estado='ACTIVA';
CREATE INDEX ix_concepto_periodo_consulta ON concepto_empleado_periodo(institucion_id,empleado_id,periodo_id,id);
CREATE TABLE concepto_empleado_periodo_historial (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, asignacion_id BIGINT NOT NULL REFERENCES concepto_empleado_periodo(id),
 institucion_id BIGINT NOT NULL REFERENCES institucion(id), usuario_id BIGINT NOT NULL REFERENCES usuario(id),
 ocurrido_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, datos JSONB NOT NULL
);
CREATE INDEX ix_concepto_periodo_historial ON concepto_empleado_periodo_historial(asignacion_id,id);
CREATE FUNCTION proteger_concepto_empleado_periodo() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Cancela el concepto ocasional; conserva su historial'; END IF;
 IF TG_OP='UPDATE' THEN
  IF OLD.estado<>'ACTIVA' OR NEW.estado<>'CANCELADA' OR NEW.version<>OLD.version+1
    OR (to_jsonb(NEW)-ARRAY['estado','motivo_operacion','actualizado_por_id','actualizado_en','version'])
       IS DISTINCT FROM (to_jsonb(OLD)-ARRAY['estado','motivo_operacion','actualizado_por_id','actualizado_en','version']) THEN
   RAISE EXCEPTION 'El concepto ocasional sólo admite cancelación trazable; registra otro para corregir';
  END IF;
  IF EXISTS(SELECT 1 FROM nomina_aplicacion a JOIN nomina_borrador_empleado ne ON ne.borrador_id=a.borrador_id AND ne.revision=a.revision
     WHERE ne.empleado_id=OLD.empleado_id AND ne.fuentes->'ocasionales' @> jsonb_build_array(jsonb_build_object('id',OLD.id))) THEN
   RAISE EXCEPTION 'El concepto forma parte de una nómina aplicada; conserva su historia';
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_concepto_periodo_proteger BEFORE UPDATE OR DELETE ON concepto_empleado_periodo FOR EACH ROW EXECUTE FUNCTION proteger_concepto_empleado_periodo();
CREATE FUNCTION auditar_concepto_empleado_periodo() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 INSERT INTO concepto_empleado_periodo_historial(asignacion_id,institucion_id,usuario_id,datos)
 VALUES(NEW.id,NEW.institucion_id,NEW.actualizado_por_id,jsonb_build_object('antes',CASE WHEN TG_OP='UPDATE' THEN to_jsonb(OLD) END,'despues',to_jsonb(NEW)));
 RETURN NEW;
END $$;
CREATE TRIGGER tr_concepto_periodo_historia AFTER INSERT OR UPDATE ON concepto_empleado_periodo FOR EACH ROW EXECUTE FUNCTION auditar_concepto_empleado_periodo();
CREATE TRIGGER tr_concepto_periodo_historia_inmutable BEFORE UPDATE OR DELETE ON concepto_empleado_periodo_historial FOR EACH ROW EXECUTE FUNCTION proteger_personal_historial();
