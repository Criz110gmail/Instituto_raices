CREATE TABLE motivo_financiero (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institucion_id BIGINT NOT NULL REFERENCES institucion(id),
    codigo VARCHAR(50) NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    naturaleza VARCHAR(10) NOT NULL,
    categoria VARCHAR(100) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    creado_por_id BIGINT,
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_por_id BIGINT,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_motivo_financiero_naturaleza CHECK (naturaleza IN ('INGRESO', 'EGRESO', 'AMBOS')),
    CONSTRAINT ck_motivo_financiero_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX ux_motivo_financiero_codigo
    ON motivo_financiero (institucion_id, lower(codigo));

