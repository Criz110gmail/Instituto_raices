-- Agenda privada: el propietario proviene de la sesión, nunca de la captura.
CREATE TABLE pendiente_personal (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT NOT NULL REFERENCES usuario(id),
 titulo VARCHAR(180) NOT NULL CHECK (length(btrim(titulo)) > 0),
 descripcion VARCHAR(4000), fecha_compromiso DATE NOT NULL,
 estado VARCHAR(20) NOT NULL CHECK (estado IN ('PENDIENTE','EN_PROCESO','REALIZADO','CANCELADO')),
 realizado_en TIMESTAMPTZ,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, creado_por_id BIGINT,
 actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, actualizado_por_id BIGINT,
 version BIGINT NOT NULL DEFAULT 0,
 CHECK ((estado='REALIZADO') = (realizado_en IS NOT NULL))
);
CREATE INDEX ix_pendiente_usuario_fecha ON pendiente_personal(usuario_id,fecha_compromiso,id);
CREATE INDEX ix_pendiente_usuario_estado_fecha ON pendiente_personal(usuario_id,estado,fecha_compromiso,id);
CREATE INDEX ix_pendiente_avisos ON pendiente_personal(usuario_id,fecha_compromiso,id)
 WHERE estado IN ('PENDIENTE','EN_PROCESO');

-- Auditoría privada, no consultable desde la auditoría administrativa de otros usuarios.
CREATE TABLE pendiente_personal_cambio (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pendiente_id BIGINT NOT NULL REFERENCES pendiente_personal(id),
 accion VARCHAR(30) NOT NULL,
 estado VARCHAR(20) NOT NULL,
 ocurrido_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 version_pendiente BIGINT NOT NULL
);
CREATE INDEX ix_pendiente_cambio ON pendiente_personal_cambio(pendiente_id,id DESC);
CREATE FUNCTION proteger_pendiente_privado() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_TABLE_NAME='pendiente_personal_cambio' THEN
  RAISE EXCEPTION 'El historial de pendientes es inmutable';
 END IF;
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Los pendientes se cancelan, no se eliminan'; END IF;
 IF NEW.usuario_id <> OLD.usuario_id THEN RAISE EXCEPTION 'No se permite cambiar el propietario'; END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER pendiente_propietario_inmutable BEFORE UPDATE OR DELETE ON pendiente_personal
 FOR EACH ROW EXECUTE FUNCTION proteger_pendiente_privado();
CREATE TRIGGER pendiente_historial_inmutable BEFORE UPDATE OR DELETE ON pendiente_personal_cambio
 FOR EACH ROW EXECUTE FUNCTION proteger_pendiente_privado();
