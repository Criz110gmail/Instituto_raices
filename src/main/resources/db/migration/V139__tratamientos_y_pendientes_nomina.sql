-- Decisiones auditadas separadas de las fotografías originales. Sin backfill financiero.
CREATE TABLE nomina_tratamiento (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 fila_id bigint NOT NULL REFERENCES nomina_borrador_empleado(id),
 clave varchar(100) NOT NULL,
 accion varchar(12) NOT NULL CHECK(accion IN ('APLICAR','NO_APLICAR','POSPONER')),
 motivo varchar(2000) NOT NULL CHECK(btrim(motivo)<>''),
 usuario_id bigint NOT NULL REFERENCES usuario(id),
 ocurrido_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_nomina_tratamiento_fila ON nomina_tratamiento(fila_id,clave,id DESC);
CREATE TRIGGER tr_nomina_tratamiento_historia BEFORE UPDATE OR DELETE ON nomina_tratamiento FOR EACH ROW EXECUTE FUNCTION proteger_personal_historial();
CREATE VIEW nomina_tratamiento_actual AS
 SELECT DISTINCT ON(fila_id,clave) * FROM nomina_tratamiento ORDER BY fila_id,clave,id DESC;

CREATE VIEW nomina_linea_tratamiento AS
 SELECT ne.id fila_id,ne.institucion_id,ne.borrador_id,k.categoria||':'||(x->>'id') clave,
 coalesce(x->>'concepto_codigo',x->>'puesto_codigo') codigo,
 coalesce(x->>'concepto_nombre',x->>'puesto_nombre') nombre,
 CASE WHEN k.categoria='sueldos' THEN 'SUELDO' ELSE x->>'naturaleza' END naturaleza,
 (CASE WHEN k.categoria='sueldos' THEN x->>'importe_bruto' ELSE x->>'importe' END)::numeric importe,
 k.categoria,x fuente,coalesce(t.accion,'APLICAR') accion,coalesce(t.motivo,'') motivo
 FROM nomina_borrador_empleado ne
 CROSS JOIN (VALUES ('sueldos'),('conceptos'),('ocasionales')) k(categoria)
 CROSS JOIN LATERAL jsonb_array_elements(coalesce(ne.fuentes->k.categoria,'[]'::jsonb)) x
 LEFT JOIN nomina_tratamiento_actual t ON t.fila_id=ne.id AND t.clave=k.categoria||':'||(x->>'id');

CREATE VIEW nomina_fila_efectiva AS
 SELECT ne.id,ne.borrador_id,ne.revision,ne.institucion_id,ne.periodo_id,ne.empleado_id,
 ne.empleado_codigo,ne.empleado_nombre,ne.fecha_inicio,ne.fecha_fin,
 CASE WHEN coalesce(t.accion,'APLICAR')='NO_APLICAR' THEN 0 ELSE ne.sueldo END sueldo,
 CASE WHEN coalesce(t.accion,'APLICAR')='NO_APLICAR' THEN 0 ELSE ne.percepciones-coalesce(a.percepciones,0) END percepciones,
 CASE WHEN coalesce(t.accion,'APLICAR')='NO_APLICAR' THEN 0 ELSE ne.deducciones-coalesce(a.deducciones,0) END deducciones,
 CASE WHEN coalesce(t.accion,'APLICAR')='NO_APLICAR' THEN 0 ELSE ne.aportaciones END aportaciones,
 CASE WHEN coalesce(t.accion,'APLICAR')='NO_APLICAR' THEN 0 ELSE ne.propuesto-coalesce(a.percepciones,0)+coalesce(a.deducciones,0) END propuesto,
 ne.moneda,ne.fuentes,ne.sello,ne.activo,coalesce(t.accion,'APLICAR') tratamiento,
 coalesce(t.motivo,'') motivo_tratamiento
 FROM nomina_borrador_empleado ne
 LEFT JOIN nomina_tratamiento_actual t ON t.fila_id=ne.id AND t.clave='EMPLEADO'
 LEFT JOIN LATERAL (SELECT sum(importe) FILTER(WHERE naturaleza='PERCEPCION') percepciones,
 sum(importe) FILTER(WHERE naturaleza='DEDUCCION') deducciones
 FROM nomina_linea_tratamiento l WHERE l.fila_id=ne.id AND l.accion<>'APLICAR') a ON true;

-- Una obligación complementaria por empleado/revisión. El importe firmado distingue
-- percepción pendiente de recuperación pendiente; nunca se suma a otro colectivo.
CREATE TABLE nomina_pendiente (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 fila_origen_id bigint NOT NULL UNIQUE REFERENCES nomina_borrador_empleado(id),
 institucion_id bigint NOT NULL REFERENCES institucion(id),
 importe numeric(19,2) NOT NULL,
 detalle jsonb NOT NULL,
 creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE nomina_borrador ADD COLUMN pendiente_origen_id bigint UNIQUE REFERENCES nomina_pendiente(id);
CREATE TRIGGER tr_nomina_pendiente_inmutable BEFORE UPDATE OR DELETE ON nomina_pendiente FOR EACH ROW EXECUTE FUNCTION proteger_personal_historial();

CREATE FUNCTION nomina_estado_vigente(p_borrador bigint) RETURNS varchar LANGUAGE sql STABLE AS $$
 SELECT CASE WHEN
  EXISTS(SELECT 1 FROM nomina_fila_efectiva ne WHERE ne.borrador_id=p_borrador AND ne.revision=b.revision_actual
   AND ne.tratamiento<>'NO_APLICAR' AND NOT EXISTS(SELECT 1 FROM nomina_pago_intento ni WHERE ni.fila_id=ne.id AND ni.estado='PAGADO'))
  OR EXISTS(SELECT 1 FROM nomina_pendiente np JOIN nomina_borrador_empleado origen ON origen.id=np.fila_origen_id
    WHERE origen.borrador_id=p_borrador AND NOT EXISTS(SELECT 1 FROM nomina_borrador hijo JOIN nomina_borrador_empleado ne ON ne.borrador_id=hijo.id
     JOIN nomina_pago_intento ni ON ni.fila_id=ne.id AND ni.estado='PAGADO' WHERE hijo.pendiente_origen_id=np.id))
 THEN CASE WHEN EXISTS(SELECT 1 FROM nomina_borrador_empleado ne JOIN nomina_pago_intento ni ON ni.fila_id=ne.id AND ni.estado='PAGADO' WHERE ne.borrador_id=p_borrador) THEN 'PARCIALMENTE_PAGADA' ELSE 'AUTORIZADA' END
 ELSE 'PAGADA' END FROM nomina_borrador b WHERE b.id=p_borrador
$$;

-- Conserva todos los controles previos y sustituye únicamente el origen del neto/estado.
DO $$ DECLARE d text; anterior text; BEGIN
 d:=pg_get_functiondef('proteger_intento_nomina()'::regprocedure);
 d:=replace(d,'nomina_borrador_empleado ne JOIN nomina_autorizacion','nomina_fila_efectiva ne JOIN nomina_autorizacion');
 EXECUTE d;
 d:=pg_get_functiondef('proteger_nomina_borrador()'::regprocedure);
 anterior:='(SELECT CASE WHEN count(ni.id)=0 THEN ''AUTORIZADA'' WHEN count(ni.id)=count(*) THEN ''PAGADA'' ELSE ''PARCIALMENTE_PAGADA'' END FROM nomina_borrador_empleado ne LEFT JOIN nomina_pago_intento ni ON ni.fila_id=ne.id AND ni.estado=''PAGADO'' WHERE ne.borrador_id=NEW.id AND ne.revision=NEW.revision_actual)';
 IF strpos(d,anterior)=0 THEN RAISE EXCEPTION 'Revisar control de estado antes de migrar tratamientos'; END IF;
 EXECUTE replace(d,anterior,'nomina_estado_vigente(NEW.id)');
 d:=pg_get_functiondef('validar_autorizacion_nomina()'::regprocedure);
 EXECUTE replace(replace(d,'nomina_borrador_empleado ne','nomina_fila_efectiva ne'),'AND ne.propuesto<=0','AND ne.tratamiento<>''NO_APLICAR'' AND ne.propuesto<=0');
END $$;

CREATE FUNCTION validar_tratamiento_nomina() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF NOT EXISTS(SELECT 1 FROM nomina_borrador_empleado ne JOIN nomina_borrador b ON b.id=ne.borrador_id
 JOIN usuario u ON u.id=NEW.usuario_id AND u.institucion_id=ne.institucion_id
 WHERE ne.id=NEW.fila_id AND ne.revision=b.revision_actual AND ne.activo AND b.estado='BORRADOR')
 THEN RAISE EXCEPTION 'Sólo se decide sobre la revisión actual de un borrador'; END IF;
 IF NEW.clave<>'EMPLEADO' AND NOT EXISTS(SELECT 1 FROM nomina_linea_tratamiento l WHERE l.fila_id=NEW.fila_id AND l.clave=NEW.clave AND l.naturaleza IN ('PERCEPCION','DEDUCCION'))
 THEN RAISE EXCEPTION 'Concepto no disponible para tratamiento'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_nomina_tratamiento_validar BEFORE INSERT ON nomina_tratamiento FOR EACH ROW EXECUTE FUNCTION validar_tratamiento_nomina();

CREATE FUNCTION registrar_pendiente_nomina() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 INSERT INTO nomina_pendiente(fila_origen_id,institucion_id,importe,detalle)
 SELECT ne.id,ne.institucion_id,sum(CASE WHEN l.naturaleza='DEDUCCION' THEN -l.importe ELSE l.importe END),
 jsonb_agg(jsonb_build_object('clave',l.clave,'codigo',l.codigo,'nombre',l.nombre,'naturaleza',l.naturaleza,'importe',l.importe,'motivo',l.motivo,'fuente',l.fuente) ORDER BY l.clave)
 FROM nomina_fila_efectiva ne JOIN nomina_linea_tratamiento l ON l.fila_id=ne.id AND l.accion='POSPONER'
 WHERE ne.borrador_id=NEW.borrador_id AND ne.revision=NEW.revision AND ne.tratamiento='APLICAR'
 GROUP BY ne.id,ne.institucion_id;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_nomina_pendientes_autorizar AFTER INSERT ON nomina_autorizacion FOR EACH ROW EXECUTE FUNCTION registrar_pendiente_nomina();

CREATE FUNCTION actualizar_origen_pendiente_nomina() RETURNS trigger LANGUAGE plpgsql AS $$ DECLARE origen bigint; BEGIN
 SELECT ne.borrador_id INTO origen FROM nomina_borrador_empleado h JOIN nomina_borrador b ON b.id=h.borrador_id
 JOIN nomina_pendiente p ON p.id=b.pendiente_origen_id JOIN nomina_borrador_empleado ne ON ne.id=p.fila_origen_id WHERE h.id=NEW.fila_id;
 IF origen IS NOT NULL THEN
  UPDATE nomina_borrador SET estado=nomina_estado_vigente(origen),version=version+1,
   motivo_operacion='Actualización de pago individual de conceptos pospuestos',actualizado_por_id=NEW.usuario_id,actualizado_en=CURRENT_TIMESTAMP WHERE id=origen;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_nomina_pendiente_estado AFTER INSERT OR UPDATE ON nomina_pago_intento FOR EACH ROW EXECUTE FUNCTION actualizar_origen_pendiente_nomina();
