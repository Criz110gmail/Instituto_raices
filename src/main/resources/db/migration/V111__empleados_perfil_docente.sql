-- Identidad canónica de personal; conserva maestros, usuarios e historial académico.
CREATE TABLE empleado (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 institucion_id BIGINT NOT NULL REFERENCES institucion(id),
 codigo VARCHAR(50) NOT NULL,
 nombres VARCHAR(150) NOT NULL, primer_apellido VARCHAR(100) NOT NULL,
 segundo_apellido VARCHAR(100), email VARCHAR(254), telefono VARCHAR(30),
 fotografia_archivo_id BIGINT UNIQUE REFERENCES archivo(id),
 maestro_origen_id BIGINT UNIQUE REFERENCES maestro(id),
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, creado_por_id BIGINT,
 actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, actualizado_por_id BIGINT,
 version BIGINT NOT NULL DEFAULT 0,
 UNIQUE(institucion_id,codigo), UNIQUE(id,institucion_id),
 CHECK(btrim(codigo)<>'' AND btrim(nombres)<>'' AND btrim(primer_apellido)<>'')
);
