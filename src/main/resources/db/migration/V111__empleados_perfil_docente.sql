CREATE TABLE empleado_laboral (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empleado_id BIGINT NOT NULL UNIQUE REFERENCES empleado(id),
 puesto VARCHAR(150), fecha_ingreso DATE,
 situacion VARCHAR(20) NOT NULL DEFAULT 'POR_CONFIRMAR',
 fecha_baja DATE, motivo_baja VARCHAR(2000),
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, creado_por_id BIGINT,
 actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, actualizado_por_id BIGINT,
 version BIGINT NOT NULL DEFAULT 0,
 CHECK(situacion IN ('POR_CONFIRMAR','ACTIVO','BAJA')),
 CHECK(situacion<>'ACTIVO' OR (fecha_ingreso IS NOT NULL AND nullif(btrim(puesto),'') IS NOT NULL)),
 CHECK(situacion<>'BAJA' OR (fecha_baja IS NOT NULL AND nullif(btrim(motivo_baja),'') IS NOT NULL)),
 CHECK(fecha_baja IS NULL OR fecha_ingreso IS NULL OR fecha_baja>=fecha_ingreso)
);
INSERT INTO empleado_laboral(empleado_id) SELECT id FROM empleado;
CREATE TABLE empleado_laboral_historial (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empleado_id BIGINT NOT NULL REFERENCES empleado(id),
 ocurrido_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 usuario_id BIGINT, version BIGINT NOT NULL, datos JSONB NOT NULL
);
CREATE INDEX ix_empleado_laboral_historial ON empleado_laboral_historial(empleado_id,id DESC);
CREATE FUNCTION registrar_historia_laboral() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO empleado_laboral_historial(empleado_id,usuario_id,version,datos)
 VALUES(NEW.empleado_id,NEW.actualizado_por_id,NEW.version,jsonb_build_object('puesto',NEW.puesto,'fechaIngreso',NEW.fecha_ingreso,'situacion',NEW.situacion,'fechaBaja',NEW.fecha_baja,'motivoBaja',NEW.motivo_baja));
 RETURN NEW;
END $$;
CREATE TRIGGER tr_historia_laboral AFTER INSERT OR UPDATE ON empleado_laboral FOR EACH ROW EXECUTE FUNCTION registrar_historia_laboral();
CREATE FUNCTION proteger_personal_historial() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'El historial laboral es inmutable'; END $$;
CREATE TRIGGER tr_historia_laboral_inmutable BEFORE UPDATE OR DELETE ON empleado_laboral_historial FOR EACH ROW EXECUTE FUNCTION proteger_personal_historial();

CREATE TABLE empleado_plantel (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empleado_id BIGINT NOT NULL REFERENCES empleado(id),
 plantel_id BIGINT NOT NULL REFERENCES plantel(id),
 fecha_inicio DATE NOT NULL, fecha_fin DATE,
 principal BOOLEAN NOT NULL DEFAULT FALSE,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, creado_por_id BIGINT,
 actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, actualizado_por_id BIGINT,
 version BIGINT NOT NULL DEFAULT 0,
 CHECK(fecha_fin IS NULL OR fecha_fin>=fecha_inicio),
 EXCLUDE USING gist(empleado_id WITH =,plantel_id WITH =,daterange(fecha_inicio,fecha_fin,'[]') WITH &&),
 EXCLUDE USING gist(empleado_id WITH =,daterange(fecha_inicio,fecha_fin,'[]') WITH &&) WHERE(principal)
);
CREATE INDEX ix_empleado_nombre ON empleado(institucion_id,primer_apellido,nombres,id);
CREATE INDEX ix_empleado_plantel_empleado ON empleado_plantel(empleado_id,fecha_inicio DESC,id DESC);
CREATE FUNCTION validar_integridad_personal() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'El expediente de personal no se elimina'; END IF;
 IF TG_TABLE_NAME='empleado' THEN
   IF TG_OP='UPDATE' AND (NEW.institucion_id<>OLD.institucion_id OR NEW.maestro_origen_id IS DISTINCT FROM OLD.maestro_origen_id) THEN RAISE EXCEPTION 'La procedencia del empleado es inmutable'; END IF;
   IF NEW.fotografia_archivo_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM archivo a WHERE a.id=NEW.fotografia_archivo_id AND a.institucion_id=NEW.institucion_id) THEN RAISE EXCEPTION 'Fotografía de otra institución'; END IF;
 ELSIF TG_TABLE_NAME='empleado_plantel' THEN
   IF TG_OP='UPDATE' AND (NEW.empleado_id<>OLD.empleado_id OR NEW.plantel_id<>OLD.plantel_id OR NEW.fecha_inicio<>OLD.fecha_inicio OR NEW.principal<>OLD.principal) THEN RAISE EXCEPTION 'Conserva la asignación y registra otra vigencia'; END IF;
   IF NOT EXISTS(SELECT 1 FROM empleado e JOIN plantel p ON p.institucion_id=e.institucion_id WHERE e.id=NEW.empleado_id AND p.id=NEW.plantel_id) THEN RAISE EXCEPTION 'Plantel de otra institución'; END IF;
 ELSIF TG_TABLE_NAME='empleado_laboral' AND TG_OP='UPDATE' AND NEW.empleado_id<>OLD.empleado_id THEN RAISE EXCEPTION 'No se puede reasignar el expediente laboral';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_empleado_integridad BEFORE INSERT OR UPDATE OR DELETE ON empleado FOR EACH ROW EXECUTE FUNCTION validar_integridad_personal();
CREATE TRIGGER tr_empleado_plantel_integridad BEFORE INSERT OR UPDATE OR DELETE ON empleado_plantel FOR EACH ROW EXECUTE FUNCTION validar_integridad_personal();
CREATE TRIGGER tr_empleado_laboral_integridad BEFORE INSERT OR UPDATE OR DELETE ON empleado_laboral FOR EACH ROW EXECUTE FUNCTION validar_integridad_personal();

CREATE FUNCTION conservar_vinculo_docente() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.empleado_id IS DISTINCT FROM OLD.empleado_id THEN
   RAISE EXCEPTION 'El perfil docente no se puede trasladar a otro empleado';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_maestro_empleado_inmutable BEFORE UPDATE ON maestro FOR EACH ROW EXECUTE FUNCTION conservar_vinculo_docente();

