-- Organización administrativa. No genera nóminas, salarios, pagos ni movimientos.
CREATE TABLE calendario_nomina (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 institucion_id BIGINT NOT NULL REFERENCES institucion(id),
 codigo VARCHAR(50) NOT NULL, nombre VARCHAR(150) NOT NULL, descripcion VARCHAR(2000),
 frecuencia VARCHAR(12) NOT NULL CHECK(frecuencia IN ('MENSUAL','QUINCENAL','SEMANAL')),
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, creado_por_id BIGINT NOT NULL REFERENCES usuario(id),
 actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, actualizado_por_id BIGINT NOT NULL REFERENCES usuario(id),
 version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
 UNIQUE(institucion_id,codigo), UNIQUE(id,institucion_id),
 CHECK(codigo=upper(btrim(codigo)) AND codigo ~ '^[A-Z0-9][A-Z0-9_-]{0,49}$' AND btrim(nombre)<>'')
);
CREATE TABLE periodo_nomina (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 institucion_id BIGINT NOT NULL, calendario_id BIGINT NOT NULL,
 codigo VARCHAR(50) NOT NULL, nombre VARCHAR(150) NOT NULL,
 calendario_codigo VARCHAR(50) NOT NULL, calendario_nombre VARCHAR(150) NOT NULL,
 frecuencia VARCHAR(12) NOT NULL CHECK(frecuencia IN ('MENSUAL','QUINCENAL','SEMANAL')), calendario_version BIGINT NOT NULL,
 fecha_inicio DATE NOT NULL, fecha_fin DATE NOT NULL, fecha_corte DATE NOT NULL, fecha_pago DATE NOT NULL,
 estado VARCHAR(12) NOT NULL DEFAULT 'PROGRAMADO' CHECK(estado IN ('PROGRAMADO','CANCELADO')),
 motivo_registro VARCHAR(2000) NOT NULL CHECK(btrim(motivo_registro)<>''),
 motivo_operacion VARCHAR(2000) NOT NULL CHECK(btrim(motivo_operacion)<>''),
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, creado_por_id BIGINT NOT NULL REFERENCES usuario(id),
 actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, actualizado_por_id BIGINT NOT NULL REFERENCES usuario(id),
 version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
 FOREIGN KEY(calendario_id,institucion_id) REFERENCES calendario_nomina(id,institucion_id),
 UNIQUE(calendario_id,codigo), UNIQUE(id,institucion_id),
 CHECK(codigo=upper(btrim(codigo)) AND codigo ~ '^[A-Z0-9][A-Z0-9_-]{0,49}$' AND btrim(nombre)<>''),
 CHECK(fecha_fin>=fecha_inicio AND fecha_corte>=fecha_inicio AND fecha_pago>=fecha_corte),
 EXCLUDE USING gist(calendario_id WITH =,daterange(fecha_inicio,fecha_fin,'[]') WITH &&) WHERE(estado='PROGRAMADO')
);
CREATE INDEX ix_calendario_nomina_institucion ON calendario_nomina(institucion_id,id);
CREATE INDEX ix_calendario_nomina_busqueda ON calendario_nomina USING gin ((lower(codigo||' '||nombre)) gin_trgm_ops);
CREATE INDEX ix_periodo_nomina_institucion ON periodo_nomina(institucion_id,id);
CREATE INDEX ix_periodo_nomina_fechas ON periodo_nomina(institucion_id,fecha_inicio,fecha_fin);
CREATE INDEX ix_periodo_nomina_busqueda ON periodo_nomina USING gin ((lower(codigo||' '||nombre)) gin_trgm_ops);
CREATE TABLE programacion_nomina_historial (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 institucion_id BIGINT NOT NULL REFERENCES institucion(id),
 tipo VARCHAR(12) NOT NULL CHECK(tipo IN ('CALENDARIO','PERIODO')), registro_id BIGINT NOT NULL,
 operacion VARCHAR(6) NOT NULL CHECK(operacion IN ('INSERT','UPDATE')),
 ocurrido_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, usuario_id BIGINT NOT NULL REFERENCES usuario(id),
 datos JSONB NOT NULL
);
CREATE INDEX ix_programacion_nomina_historial ON programacion_nomina_historial(institucion_id,tipo,registro_id,id DESC);
CREATE FUNCTION proteger_programacion_nomina() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Conserva la programación de nómina y su historial'; END IF;
 IF (NEW.id,NEW.institucion_id,NEW.creado_en,NEW.creado_por_id) IS DISTINCT FROM (OLD.id,OLD.institucion_id,OLD.creado_en,OLD.creado_por_id) THEN
  RAISE EXCEPTION 'La identidad y la institución no cambian';
 END IF;
 IF TG_TABLE_NAME='calendario_nomina' THEN
  IF NEW.frecuencia<>OLD.frecuencia AND EXISTS(SELECT 1 FROM periodo_nomina WHERE calendario_id=OLD.id) THEN
   RAISE EXCEPTION 'Un calendario con periodos conserva su frecuencia; crea otro calendario';
  END IF;
 ELSE
  IF OLD.estado='CANCELADO' OR (NEW.calendario_id,NEW.calendario_codigo,NEW.calendario_nombre,NEW.frecuencia,NEW.calendario_version,NEW.motivo_registro)
     IS DISTINCT FROM (OLD.calendario_id,OLD.calendario_codigo,OLD.calendario_nombre,OLD.frecuencia,OLD.calendario_version,OLD.motivo_registro) THEN
   RAISE EXCEPTION 'El periodo conserva calendario y motivo originales; un cancelado es sólo consulta';
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_calendario_nomina_proteger BEFORE UPDATE OR DELETE ON calendario_nomina FOR EACH ROW EXECUTE FUNCTION proteger_programacion_nomina();
CREATE TRIGGER tr_periodo_nomina_proteger BEFORE UPDATE OR DELETE ON periodo_nomina FOR EACH ROW EXECUTE FUNCTION proteger_programacion_nomina();
CREATE FUNCTION registrar_historia_programacion_nomina() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 INSERT INTO programacion_nomina_historial(institucion_id,tipo,registro_id,operacion,usuario_id,datos)
 VALUES(NEW.institucion_id,CASE WHEN TG_TABLE_NAME='calendario_nomina' THEN 'CALENDARIO' ELSE 'PERIODO' END,NEW.id,TG_OP,NEW.actualizado_por_id,
 jsonb_build_object('antes',CASE WHEN TG_OP='UPDATE' THEN to_jsonb(OLD) ELSE NULL END,'despues',to_jsonb(NEW)));
 RETURN NEW;
END $$;
CREATE TRIGGER tr_calendario_nomina_historia AFTER INSERT OR UPDATE ON calendario_nomina FOR EACH ROW EXECUTE FUNCTION registrar_historia_programacion_nomina();
CREATE TRIGGER tr_periodo_nomina_historia AFTER INSERT OR UPDATE ON periodo_nomina FOR EACH ROW EXECUTE FUNCTION registrar_historia_programacion_nomina();
CREATE TRIGGER tr_programacion_nomina_historia_inmutable BEFORE UPDATE OR DELETE ON programacion_nomina_historial FOR EACH ROW EXECUTE FUNCTION proteger_personal_historial();
