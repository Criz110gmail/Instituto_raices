-- Catálogo privado sin importes, asignaciones, préstamos, cálculo fiscal ni movimientos.
CREATE TABLE concepto_nomina (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 institucion_id BIGINT NOT NULL REFERENCES institucion(id),
 codigo VARCHAR(50) NOT NULL, nombre VARCHAR(150) NOT NULL, descripcion VARCHAR(2000),
 naturaleza VARCHAR(24) NOT NULL CHECK(naturaleza IN ('PERCEPCION','DEDUCCION','APORTACION_PATRONAL')),
 aplicacion VARCHAR(12) NOT NULL CHECK(aplicacion IN ('HABITUAL','OCASIONAL')),
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, creado_por_id BIGINT NOT NULL REFERENCES usuario(id),
 actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, actualizado_por_id BIGINT NOT NULL REFERENCES usuario(id),
 version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
 UNIQUE(institucion_id,codigo), UNIQUE(id,institucion_id),
 CHECK(codigo=upper(btrim(codigo)) AND codigo ~ '^[A-Z0-9][A-Z0-9_-]{0,49}$' AND btrim(nombre)<>'')
);
CREATE INDEX ix_concepto_nomina_institucion_nombre ON concepto_nomina(institucion_id,nombre,id);
CREATE TABLE concepto_nomina_historial (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 concepto_id BIGINT NOT NULL, institucion_id BIGINT NOT NULL,
 operacion VARCHAR(6) NOT NULL CHECK(operacion IN ('INSERT','UPDATE')),
 ocurrido_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 usuario_id BIGINT NOT NULL REFERENCES usuario(id), datos JSONB NOT NULL,
 FOREIGN KEY(concepto_id,institucion_id) REFERENCES concepto_nomina(id,institucion_id)
);
CREATE INDEX ix_concepto_nomina_historial ON concepto_nomina_historial(concepto_id,id DESC);
CREATE FUNCTION proteger_concepto_nomina() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Desactiva el concepto de nómina; no borres su historial'; END IF;
 IF (NEW.id,NEW.institucion_id,NEW.creado_en,NEW.creado_por_id) IS DISTINCT FROM (OLD.id,OLD.institucion_id,OLD.creado_en,OLD.creado_por_id) THEN
  RAISE EXCEPTION 'La identidad y la institución del concepto no cambian';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_concepto_nomina_proteger BEFORE UPDATE OR DELETE ON concepto_nomina FOR EACH ROW EXECUTE FUNCTION proteger_concepto_nomina();
CREATE FUNCTION registrar_historia_concepto_nomina() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 INSERT INTO concepto_nomina_historial(concepto_id,institucion_id,operacion,usuario_id,datos)
 VALUES(NEW.id,NEW.institucion_id,TG_OP,NEW.actualizado_por_id,
 jsonb_build_object('antes',CASE WHEN TG_OP='UPDATE' THEN to_jsonb(OLD) ELSE NULL END,'despues',to_jsonb(NEW)));
 RETURN NEW;
END $$;
CREATE TRIGGER tr_concepto_nomina_historia AFTER INSERT OR UPDATE ON concepto_nomina FOR EACH ROW EXECUTE FUNCTION registrar_historia_concepto_nomina();
