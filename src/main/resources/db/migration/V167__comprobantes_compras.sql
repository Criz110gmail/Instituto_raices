-- Expediente privado: no modifica compras, cuentas ni movimientos existentes.
CREATE TABLE compra_respaldo (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 compra_id bigint NOT NULL REFERENCES compra(id),
 tipo varchar(20) NOT NULL CHECK(tipo IN ('SIN_COMPROBANTE','TICKET_RECIBO','CFDI')),
 justificacion varchar(2000) NOT NULL DEFAULT '',
 creado_por_id bigint NOT NULL REFERENCES usuario(id),
 creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(tipo<>'SIN_COMPROBANTE' OR btrim(justificacion)<>'')
);
CREATE INDEX ix_compra_respaldo ON compra_respaldo(compra_id,id DESC);
CREATE TRIGGER tr_compra_respaldo_historia BEFORE UPDATE OR DELETE ON compra_respaldo
 FOR EACH ROW EXECUTE FUNCTION proteger_personal_historial();

CREATE TABLE compra_documento (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 compra_id bigint NOT NULL REFERENCES compra(id),
 archivo_id bigint NOT NULL UNIQUE REFERENCES archivo(id),
 tipo varchar(12) NOT NULL CHECK(tipo IN ('PDF','IMAGEN','XML')),
 descripcion varchar(300) NOT NULL DEFAULT '',
 justificacion varchar(2000) NOT NULL DEFAULT '',
 creado_por_id bigint NOT NULL REFERENCES usuario(id),
 creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 retirado_en timestamptz,
 retirado_por_id bigint REFERENCES usuario(id),
 motivo_retiro varchar(2000),
 CHECK ((retirado_en IS NULL AND retirado_por_id IS NULL AND motivo_retiro IS NULL)
  OR (retirado_en IS NOT NULL AND retirado_por_id IS NOT NULL AND btrim(motivo_retiro)<>''))
);
CREATE INDEX ix_compra_documento ON compra_documento(compra_id,id DESC);
CREATE FUNCTION proteger_documento_compra() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'El expediente documental se conserva'; END IF;
 IF TG_OP='INSERT' THEN
  IF NOT EXISTS(SELECT 1 FROM compra c JOIN archivo a ON a.id=NEW.archivo_id AND a.institucion_id=c.institucion_id WHERE c.id=NEW.compra_id)
   THEN RAISE EXCEPTION 'El archivo no pertenece a la institución de la compra'; END IF;
 ELSE
  IF OLD.retirado_en IS NOT NULL OR NEW.retirado_en IS NULL
   OR (to_jsonb(NEW)-ARRAY['retirado_en','retirado_por_id','motivo_retiro']) IS DISTINCT FROM
      (to_jsonb(OLD)-ARRAY['retirado_en','retirado_por_id','motivo_retiro'])
   THEN RAISE EXCEPTION 'Sólo se permite retirar el documento conservando su historia'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_compra_documento BEFORE INSERT OR UPDATE OR DELETE ON compra_documento
 FOR EACH ROW EXECUTE FUNCTION proteger_documento_compra();

CREATE TABLE compra_cfdi (
 documento_id bigint PRIMARY KEY REFERENCES compra_documento(id),
 institucion_id bigint NOT NULL REFERENCES institucion(id),
 uuid varchar(36) NOT NULL,
 version_cfdi varchar(3) NOT NULL,
 serie varchar(100) NOT NULL,
 folio varchar(100) NOT NULL,
 fecha timestamp NOT NULL,
 emisor_rfc varchar(13) NOT NULL,
 emisor_nombre varchar(300) NOT NULL,
 receptor_rfc varchar(13) NOT NULL,
 receptor_nombre varchar(300) NOT NULL,
 moneda varchar(3) NOT NULL,
 tipo_comprobante varchar(1) NOT NULL,
 subtotal numeric(19,6) NOT NULL,
 descuento numeric(19,6) NOT NULL,
 total numeric(19,6) NOT NULL,
 UNIQUE(institucion_id,uuid)
);
CREATE TABLE compra_cfdi_concepto (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 documento_id bigint NOT NULL REFERENCES compra_cfdi(documento_id),
 orden integer NOT NULL,
 clave_producto varchar(20) NOT NULL,
 clave_unidad varchar(20) NOT NULL,
 descripcion varchar(1000) NOT NULL,
 cantidad numeric(19,6) NOT NULL CHECK(cantidad>0),
 valor_unitario numeric(19,6) NOT NULL,
 importe numeric(19,6) NOT NULL,
 descuento numeric(19,6) NOT NULL,
 UNIQUE(documento_id,orden)
);
CREATE FUNCTION validar_cfdi_compra() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF NEW.uuid<>upper(NEW.uuid) OR NOT EXISTS(
  SELECT 1 FROM compra_documento d JOIN compra c ON c.id=d.compra_id
  WHERE d.id=NEW.documento_id AND d.tipo='XML' AND c.institucion_id=NEW.institucion_id)
 THEN RAISE EXCEPTION 'El CFDI debe corresponder al documento XML y la institución de la compra'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_validar_cfdi_compra BEFORE INSERT ON compra_cfdi
 FOR EACH ROW EXECUTE FUNCTION validar_cfdi_compra();
CREATE TABLE compra_cfdi_impuesto (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 documento_id bigint NOT NULL REFERENCES compra_cfdi(documento_id),
 concepto_orden integer,
 tipo varchar(12) NOT NULL CHECK(tipo IN ('TRASLADO','RETENCION')),
 impuesto varchar(3) NOT NULL,
 factor varchar(10) NOT NULL,
 tasa numeric(19,6),
 base numeric(19,6),
 importe numeric(19,6)
);
CREATE INDEX ix_compra_cfdi_impuesto ON compra_cfdi_impuesto(documento_id,concepto_orden);
CREATE TABLE compra_cfdi_relacion (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 documento_id bigint NOT NULL REFERENCES compra_cfdi(documento_id),
 tipo varchar(2) NOT NULL,
 uuid varchar(36) NOT NULL
);
CREATE INDEX ix_compra_cfdi_relacion ON compra_cfdi_relacion(documento_id);
CREATE TABLE compra_cfdi_importacion (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 documento_id bigint NOT NULL REFERENCES compra_cfdi(documento_id),
 compra_id bigint NOT NULL REFERENCES compra(id),
 version_anterior bigint NOT NULL,
 motivo varchar(2000) NOT NULL CHECK(btrim(motivo)<>''),
 creado_por_id bigint NOT NULL REFERENCES usuario(id),
 creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
DO $$ DECLARE tabla text; BEGIN
 FOREACH tabla IN ARRAY ARRAY['compra_cfdi','compra_cfdi_concepto','compra_cfdi_impuesto','compra_cfdi_relacion','compra_cfdi_importacion'] LOOP
  EXECUTE format('CREATE TRIGGER tr_historia BEFORE UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION proteger_personal_historial()',tabla);
 END LOOP;
END $$;
