-- Configuración aditiva: ningún dato laboral/salario anterior se infiere ni modifica.
CREATE TABLE jornada_laboral (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 institucion_id BIGINT NOT NULL REFERENCES institucion(id),
 codigo VARCHAR(50) NOT NULL, nombre VARCHAR(150) NOT NULL, descripcion VARCHAR(2000),
 horas_semanales NUMERIC(5,2) NOT NULL CHECK(horas_semanales>0 AND horas_semanales<=168),
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, creado_por_id BIGINT NOT NULL REFERENCES usuario(id),
 actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, actualizado_por_id BIGINT NOT NULL REFERENCES usuario(id), version BIGINT NOT NULL DEFAULT 0,
 UNIQUE(institucion_id,codigo),UNIQUE(id,institucion_id),
 CHECK(codigo=upper(btrim(codigo)) AND codigo<>'' AND btrim(nombre)<>'')
);
CREATE TABLE esquema_remuneracion (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 institucion_id BIGINT NOT NULL REFERENCES institucion(id),
 codigo VARCHAR(50) NOT NULL, nombre VARCHAR(150) NOT NULL, descripcion VARCHAR(2000),
 puesto_id BIGINT NOT NULL,jornada_id BIGINT NOT NULL,
 importe_bruto NUMERIC(19,2) NOT NULL CHECK(importe_bruto>0),moneda VARCHAR(3) NOT NULL CHECK(moneda ~ '^[A-Z]{3}$'),
 base VARCHAR(20) NOT NULL CHECK(base IN ('MENSUAL','SEMANAL','DIARIA','POR_HORA')),
 frecuencia VARCHAR(20) NOT NULL CHECK(frecuencia IN ('MENSUAL','QUINCENAL','SEMANAL')),
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,creado_por_id BIGINT NOT NULL REFERENCES usuario(id),
 actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,actualizado_por_id BIGINT NOT NULL REFERENCES usuario(id),version BIGINT NOT NULL DEFAULT 0,
 UNIQUE(institucion_id,codigo),UNIQUE(id,institucion_id),
 FOREIGN KEY(puesto_id,institucion_id) REFERENCES puesto_laboral(id,institucion_id),
 FOREIGN KEY(jornada_id,institucion_id) REFERENCES jornada_laboral(id,institucion_id),
 CHECK(codigo=upper(btrim(codigo)) AND codigo<>'' AND btrim(nombre)<>'')
);
CREATE TABLE asignacion_esquema_laboral (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 institucion_id BIGINT NOT NULL,empleado_id BIGINT NOT NULL,condicion_id BIGINT NOT NULL UNIQUE,
 esquema_id BIGINT NOT NULL,esquema_version BIGINT NOT NULL,esquema_codigo VARCHAR(50) NOT NULL,esquema_nombre VARCHAR(150) NOT NULL,
 jornada_id BIGINT NOT NULL,jornada_version BIGINT NOT NULL,jornada_codigo VARCHAR(50) NOT NULL,jornada_nombre VARCHAR(150) NOT NULL,
 jornada_descripcion VARCHAR(2000),horas_semanales NUMERIC(5,2) NOT NULL CHECK(horas_semanales>0 AND horas_semanales<=168),
 puesto_version BIGINT NOT NULL,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,creado_por_id BIGINT NOT NULL REFERENCES usuario(id),
 FOREIGN KEY(empleado_id,institucion_id) REFERENCES empleado(id,institucion_id),
 FOREIGN KEY(condicion_id,empleado_id) REFERENCES condicion_salarial(id,empleado_id),
 FOREIGN KEY(esquema_id,institucion_id) REFERENCES esquema_remuneracion(id,institucion_id),
 FOREIGN KEY(jornada_id,institucion_id) REFERENCES jornada_laboral(id,institucion_id)
);
CREATE INDEX ix_jornada_institucion ON jornada_laboral(institucion_id,nombre,id);
CREATE INDEX ix_esquema_institucion ON esquema_remuneracion(institucion_id,nombre,id);
CREATE INDEX ix_asignacion_esquema_empleado ON asignacion_esquema_laboral(empleado_id,condicion_id);
CREATE FUNCTION proteger_catalogo_laboral() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Desactiva el catálogo; no se elimina historial'; END IF;
 IF NEW.institucion_id<>OLD.institucion_id THEN RAISE EXCEPTION 'No se cambia institución del catálogo'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_jornada_proteger BEFORE UPDATE OR DELETE ON jornada_laboral FOR EACH ROW EXECUTE FUNCTION proteger_catalogo_laboral();
CREATE TRIGGER tr_esquema_proteger BEFORE UPDATE OR DELETE ON esquema_remuneracion FOR EACH ROW EXECUTE FUNCTION proteger_catalogo_laboral();
CREATE TRIGGER tr_asignacion_inmutable BEFORE UPDATE OR DELETE ON asignacion_esquema_laboral FOR EACH ROW EXECUTE FUNCTION proteger_personal_historial();
CREATE FUNCTION registrar_historia_esquema() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 INSERT INTO personal_salarial_historial(institucion_id,empleado_id,tipo,registro_id,operacion,usuario_id,datos)
 VALUES(NEW.institucion_id,(to_jsonb(NEW)->>'empleado_id')::BIGINT,
 CASE TG_TABLE_NAME WHEN 'jornada_laboral' THEN 'JORNADA' WHEN 'esquema_remuneracion' THEN 'ESQUEMA' ELSE 'ASIGNACION' END,
 NEW.id,TG_OP,CASE WHEN TG_TABLE_NAME='asignacion_esquema_laboral' THEN NEW.creado_por_id ELSE (to_jsonb(NEW)->>'actualizado_por_id')::BIGINT END,
 jsonb_build_object('antes',CASE WHEN TG_OP='UPDATE' THEN to_jsonb(OLD) ELSE NULL END,'despues',to_jsonb(NEW)));
 RETURN NEW;
END $$;
CREATE TRIGGER tr_jornada_historia AFTER INSERT OR UPDATE ON jornada_laboral FOR EACH ROW EXECUTE FUNCTION registrar_historia_esquema();
CREATE TRIGGER tr_esquema_historia AFTER INSERT OR UPDATE ON esquema_remuneracion FOR EACH ROW EXECUTE FUNCTION registrar_historia_esquema();
CREATE TRIGGER tr_asignacion_historia AFTER INSERT ON asignacion_esquema_laboral FOR EACH ROW EXECUTE FUNCTION registrar_historia_esquema();
