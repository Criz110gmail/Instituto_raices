CREATE TABLE prestamo_empleado (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 institucion_id BIGINT NOT NULL REFERENCES institucion(id), empleado_id BIGINT NOT NULL,
 concepto_id BIGINT NOT NULL, concepto_codigo VARCHAR(50) NOT NULL, concepto_nombre VARCHAR(150) NOT NULL,
 concepto_version BIGINT NOT NULL, moneda VARCHAR(3) NOT NULL,
 importe NUMERIC(19,2) NOT NULL CHECK(importe>0), parcialidad NUMERIC(19,2) NOT NULL CHECK(parcialidad>0 AND parcialidad<=importe),
 primer_descuento DATE NOT NULL CHECK(extract(day from primer_descuento)=1),
 estado VARCHAR(10) NOT NULL DEFAULT 'BORRADOR' CHECK(estado IN ('BORRADOR','ACTIVO','CANCELADO')),
 solicitud UUID NOT NULL, motivo VARCHAR(2000) NOT NULL CHECK(btrim(motivo)<>''),
 motivo_operacion VARCHAR(2000) NOT NULL CHECK(btrim(motivo_operacion)<>''),
 creado_por_id BIGINT NOT NULL REFERENCES usuario(id), creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado_por_id BIGINT NOT NULL REFERENCES usuario(id), actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
 FOREIGN KEY(empleado_id,institucion_id) REFERENCES empleado(id,institucion_id),
 FOREIGN KEY(concepto_id,institucion_id) REFERENCES concepto_nomina(id,institucion_id),
 UNIQUE(institucion_id,solicitud),UNIQUE(id,institucion_id,empleado_id)
);
CREATE INDEX ix_prestamo_empleado_consulta ON prestamo_empleado(institucion_id,empleado_id,estado,id);
CREATE TABLE prestamo_entrega (
 prestamo_id BIGINT PRIMARY KEY, institucion_id BIGINT NOT NULL, empleado_id BIGINT NOT NULL,
 movimiento_id BIGINT NOT NULL UNIQUE REFERENCES movimiento_financiero(id),
 cuenta_codigo VARCHAR(50) NOT NULL, cuenta_nombre VARCHAR(150) NOT NULL,
 referencia VARCHAR(150) NOT NULL CHECK(btrim(referencia)<>''),
 importe NUMERIC(19,2) NOT NULL CHECK(importe>0), moneda VARCHAR(3) NOT NULL,
 usuario_id BIGINT NOT NULL REFERENCES usuario(id), ocurrido_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 motivo VARCHAR(2000) NOT NULL CHECK(btrim(motivo)<>''),
 FOREIGN KEY(prestamo_id,institucion_id,empleado_id) REFERENCES prestamo_empleado(id,institucion_id,empleado_id)
);
CREATE TABLE prestamo_empleado_historial (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, prestamo_id BIGINT NOT NULL REFERENCES prestamo_empleado(id),
 institucion_id BIGINT NOT NULL REFERENCES institucion(id), usuario_id BIGINT NOT NULL REFERENCES usuario(id),
 ocurrido_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, datos JSONB NOT NULL
);
CREATE INDEX ix_prestamo_historia ON prestamo_empleado_historial(prestamo_id,id);
CREATE FUNCTION proteger_prestamo_empleado() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Conserva el préstamo y su historial'; END IF;
 IF OLD.estado<>'BORRADOR' OR NEW.version<>OLD.version+1 OR
   (NEW.id,NEW.institucion_id,NEW.empleado_id,NEW.solicitud,NEW.creado_por_id,NEW.creado_en)
   IS DISTINCT FROM (OLD.id,OLD.institucion_id,OLD.empleado_id,OLD.solicitud,OLD.creado_por_id,OLD.creado_en) THEN
   RAISE EXCEPTION 'Sólo se modifica el borrador; un préstamo entregado conserva sus condiciones';
 END IF;
 IF NEW.estado<>'BORRADOR' AND
   (to_jsonb(NEW)-ARRAY['estado','motivo_operacion','actualizado_por_id','actualizado_en','version'])
   IS DISTINCT FROM (to_jsonb(OLD)-ARRAY['estado','motivo_operacion','actualizado_por_id','actualizado_en','version']) THEN
   RAISE EXCEPTION 'No cambies condiciones al entregar o cancelar el préstamo';
 END IF;
 IF NEW.estado='ACTIVO' AND NOT EXISTS(SELECT 1 FROM prestamo_entrega en JOIN movimiento_financiero m ON m.id=en.movimiento_id
   WHERE en.prestamo_id=OLD.id AND en.institucion_id=OLD.institucion_id AND en.empleado_id=OLD.empleado_id
   AND en.importe=OLD.importe AND en.moneda=OLD.moneda AND m.institucion_id=en.institucion_id
   AND m.clase='PRESTAMO' AND m.direccion='EGRESO' AND m.monto=en.importe) THEN
   RAISE EXCEPTION 'La entrega requiere un egreso único y coincidente';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_prestamo_proteger BEFORE UPDATE OR DELETE ON prestamo_empleado FOR EACH ROW EXECUTE FUNCTION proteger_prestamo_empleado();
CREATE FUNCTION auditar_prestamo_empleado() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 INSERT INTO prestamo_empleado_historial(prestamo_id,institucion_id,usuario_id,datos)
 VALUES(NEW.id,NEW.institucion_id,NEW.actualizado_por_id,jsonb_build_object('antes',CASE WHEN TG_OP='UPDATE' THEN to_jsonb(OLD) END,'despues',to_jsonb(NEW)));
 RETURN NEW;
END $$;
CREATE TRIGGER tr_prestamo_historia AFTER INSERT OR UPDATE ON prestamo_empleado FOR EACH ROW EXECUTE FUNCTION auditar_prestamo_empleado();
CREATE TRIGGER tr_prestamo_historia_inmutable BEFORE UPDATE OR DELETE ON prestamo_empleado_historial FOR EACH ROW EXECUTE FUNCTION proteger_personal_historial();
CREATE TRIGGER tr_prestamo_entrega_inmutable BEFORE UPDATE OR DELETE ON prestamo_entrega FOR EACH ROW EXECUTE FUNCTION proteger_personal_historial();
