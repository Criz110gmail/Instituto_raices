-- Configuración privada: no crea nóminas, pagos, retenciones ni movimientos financieros.
CREATE TABLE concepto_empleado (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 institucion_id BIGINT NOT NULL, empleado_id BIGINT NOT NULL, concepto_id BIGINT NOT NULL,
 concepto_codigo VARCHAR(50) NOT NULL, concepto_nombre VARCHAR(150) NOT NULL,
 naturaleza VARCHAR(24) NOT NULL CHECK(naturaleza IN ('PERCEPCION','DEDUCCION','APORTACION_PATRONAL')),
 aplicacion VARCHAR(12) NOT NULL CHECK(aplicacion='HABITUAL'), concepto_version BIGINT NOT NULL,
 importe NUMERIC(19,2) NOT NULL CHECK(importe>0), moneda VARCHAR(3) NOT NULL CHECK(moneda ~ '^[A-Z]{3}$'),
 fecha_inicio DATE NOT NULL, fecha_fin DATE, estado VARCHAR(12) NOT NULL DEFAULT 'ACTIVA' CHECK(estado IN ('ACTIVA','CANCELADA')),
 motivo VARCHAR(2000) NOT NULL CHECK(btrim(motivo)<>''), motivo_operacion VARCHAR(2000) NOT NULL CHECK(btrim(motivo_operacion)<>''),
 anterior_id BIGINT, fin_anterior DATE,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, creado_por_id BIGINT NOT NULL REFERENCES usuario(id),
 actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, actualizado_por_id BIGINT NOT NULL REFERENCES usuario(id),
 version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
 FOREIGN KEY(empleado_id,institucion_id) REFERENCES empleado(id,institucion_id),
 FOREIGN KEY(concepto_id,institucion_id) REFERENCES concepto_nomina(id,institucion_id),
 UNIQUE(id,empleado_id,concepto_id),
 FOREIGN KEY(anterior_id,empleado_id,concepto_id) REFERENCES concepto_empleado(id,empleado_id,concepto_id),
 CHECK(fecha_fin IS NULL OR fecha_fin>=fecha_inicio), CHECK(anterior_id IS NULL OR anterior_id<>id),
 EXCLUDE USING gist(empleado_id WITH =,concepto_id WITH =,daterange(fecha_inicio,fecha_fin,'[]') WITH &&) WHERE(estado='ACTIVA')
);
CREATE INDEX ix_concepto_empleado_institucion ON concepto_empleado(institucion_id,id);
CREATE INDEX ix_concepto_empleado_concepto ON concepto_empleado(institucion_id,concepto_id,id);
CREATE INDEX ix_concepto_empleado_fechas ON concepto_empleado(institucion_id,fecha_inicio,fecha_fin);
CREATE TABLE concepto_empleado_historial (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asignacion_id BIGINT NOT NULL REFERENCES concepto_empleado(id), institucion_id BIGINT NOT NULL REFERENCES institucion(id),
 operacion VARCHAR(6) NOT NULL CHECK(operacion IN ('INSERT','UPDATE')),
 ocurrido_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, usuario_id BIGINT NOT NULL REFERENCES usuario(id), datos JSONB NOT NULL
);
CREATE INDEX ix_concepto_empleado_historial ON concepto_empleado_historial(asignacion_id,id DESC);
CREATE FUNCTION proteger_concepto_empleado() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Conserva el concepto asignado y su historial'; END IF;
 IF (to_jsonb(NEW)-ARRAY['fecha_fin','estado','motivo_operacion','actualizado_en','actualizado_por_id','version'])
    IS DISTINCT FROM (to_jsonb(OLD)-ARRAY['fecha_fin','estado','motivo_operacion','actualizado_en','actualizado_por_id','version']) OR OLD.estado='CANCELADA' THEN
  RAISE EXCEPTION 'La asignación conserva su fotografía original; programa una nueva vigencia';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_concepto_empleado_proteger BEFORE UPDATE OR DELETE ON concepto_empleado FOR EACH ROW EXECUTE FUNCTION proteger_concepto_empleado();
CREATE FUNCTION registrar_historia_concepto_empleado() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 INSERT INTO concepto_empleado_historial(asignacion_id,institucion_id,operacion,usuario_id,datos)
 VALUES(NEW.id,NEW.institucion_id,TG_OP,NEW.actualizado_por_id,
 jsonb_build_object('antes',CASE WHEN TG_OP='UPDATE' THEN to_jsonb(OLD) ELSE NULL END,'despues',to_jsonb(NEW)));
 RETURN NEW;
END $$;
CREATE TRIGGER tr_concepto_empleado_historia AFTER INSERT OR UPDATE ON concepto_empleado FOR EACH ROW EXECUTE FUNCTION registrar_historia_concepto_empleado();
CREATE TRIGGER tr_concepto_empleado_historia_inmutable BEFORE UPDATE OR DELETE ON concepto_empleado_historial FOR EACH ROW EXECUTE FUNCTION proteger_personal_historial();
